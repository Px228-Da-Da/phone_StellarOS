/*
 * uspace.c — как программа попадает в пользовательский режим.
 *
 * Порядок такой:
 *   1. завести программе своё адресное пространство;
 *   2. взять страницы под код и стек у постраничного аллокатора;
 *   3. скопировать в них программу и согласовать кэши — иначе процессор
 *      выберет из памяти то, что лежало там до копирования;
 *   4. отобразить эти страницы в её пространстве с правами для EL0:
 *      код — читать и исполнять, стек — читать и писать;
 *   5. завести задачу планировщика, которая первым же делом уйдёт в EL0
 *      и больше оттуда не вернётся.
 *
 * Пятый шаг объясняет, почему процесс здесь — это задача планировщика, а
 * не что-то отдельное. У программы в EL0 всё равно должен быть стек в
 * EL1: на него процессор складывает кадр при каждом системном вызове и
 * каждом прерывании. Этот стек — и есть стек задачи, а планировщику при
 * переключении неважно, где задача находилась, в ядре или в программе:
 * он видит только сохранённый указатель стека и номер пространства.
 *
 * Чего здесь ещё нет: освобождения. Страницы завершившейся программы и
 * её таблицы остаются занятыми. Сборщик появится вместе с ожиданием
 * завершения — сейчас освобождать их некому и незачем, программы
 * запускаются один раз при старте.
 */
#include "uspace.h"
#include "mmu.h"
#include "pmm.h"
#include "sched.h"
#include "kmalloc.h"
#include "string.h"
#include "print.h"
#include "io.h"

/* Спуск в EL0, switch.S */
extern void enter_el0(u64 pc, u64 sp);

/*
 * Где живут программы.
 *
 * Адрес ОДИН И ТОТ ЖЕ для всех: пространства раздельные, и одинаковый
 * виртуальный адрес у двух программ означает разные страницы памяти.
 * Так устроены все настоящие системы, и так же устроена проверка этой
 * раздельности — двойник, запущенный дважды, пишет по одному адресу и
 * не видит соседа.
 *
 * Почему не с нуля, как принято. Ядро отображено единично: виртуальный
 * адрес равен физическому, поэтому вся нижняя часть пространства занята
 * периферией и памятью, и эти отображения есть в каждом пространстве —
 * без них некуда было бы возвращаться из прерывания. Берём заведомо
 * пустой кусок повыше: 64 ГБ при верхней границе в 512.
 */
#define USER_BASE       0x0000001000000000UL
#define USER_DATA_OFF   0x0000000000080000UL    /* изменяемые данные       */
/*
 * Изменяемые данные программы: 256 КБ.
 *
 * Было 64. Столько занимала куча объектов виртуальной машины, когда её
 * увеличили, и компоновщик отказался собирать исполнитель — что и
 * правильно: предел лучше встретить на сборке, чем на телефоне.
 *
 * Шестьдесят четыре килобайта для программы на телефоне с четырьмя
 * гигабайтами — скупость без причины. Страницы выделяются по факту
 * запуска, и неиспользованное никому не мешает.
 *
 * Число обязано совпадать с проверкой в user/user.ld: там стоит тот же
 * предел, и разойдись они — программа собралась бы, а при запуске
 * молча писала бы мимо своей памяти.
 */
#define USER_DATA_PAGES  64                     /* 256 КБ, как в user.ld   */
#define USER_STACK_OFF  0x0000000000100000UL    /* стек в мегабайте от кода */
#define USER_STACK_PAGES 2

struct uproc {
    u64 entry;      /* с какого адреса начинать         */
    u64 sp;         /* вершина пользовательского стека  */
};

/*
 * Точка входа задачи. Всё, что здесь происходит в EL1, — это одна
 * строка отчёта; дальше начинается пользовательский режим.
 */
static void user_trampoline(void *arg)
{
    struct uproc *p = arg;
    u64 entry = p->entry;
    u64 sp = p->sp;

    /* Описание больше не нужно: два числа из него уже у нас в регистрах,
     * а обратно в эту функцию управление не вернётся — освободить его
     * потом будет некому. */
    kfree(p);

    enter_el0(entry, sp);
}

volatile u32 uspace_stage;
const char *volatile uspace_who;

s64 uspace_spawn(const char *name, const void *image, u64 size)
{
    struct uproc *p;
    struct task *t;
    void *code, *data, *stack;
    u64 root, code_bytes;
    u32 code_pages;

    if (!size)
        return -1;

    code_pages = (u32)((size + PAGE_SIZE - 1) / PAGE_SIZE);
    code_bytes = (u64)code_pages * PAGE_SIZE;

    uspace_who = name;
    uspace_stage = 1;                   /* куча */
    p = kzalloc(sizeof(*p));
    if (!p)
        return -1;

    uspace_stage = 2;                   /* адресное пространство */
    root = mmu_new_user_space();
    if (!root) {
        kprintf("EL0      : %s НЕ ЗАПУЩЕНА — НЕТ ПРОСТРАНСТВА\n", name);
        return -1;
    }

    uspace_stage = 3;                   /* страницы */
    code  = pmm_alloc_pages(code_pages);
    data  = pmm_alloc_pages(USER_DATA_PAGES);
    stack = pmm_alloc_pages(USER_STACK_PAGES);
    if (!code || !data || !stack) {
        kprintf("EL0      : %s НЕ ЗАПУЩЕНА — НЕТ ПАМЯТИ\n", name);
        return -1;
    }

    uspace_stage = 4;                   /* копирование */
    memcpy(code, image, size);

    /*
     * Программу мы только что записали как данные, а исполняться она
     * будет через кэш инструкций. Согласовать их обязательно, и именно
     * по ядерному адресу: по пользовательскому трансляции ещё нет, да и
     * действует она только в чужом пространстве.
     */
    uspace_stage = 5;                   /* согласование кэшей */
    mmu_sync_icache((u64)(uintptr_t)code, code_bytes);

    uspace_stage = 6;                   /* отображение */
    /*
     * Три области, и права у всех разные.
     *
     * Код — читать и исполнять: программа не должна мочь переписать
     * саму себя, и это не предосторожность ради красоты, а то, что
     * ловит половину ошибок с указателями сразу.
     *
     * Изменяемые данные — отдельно и только на чтение-запись. У программ
     * на ассемблере их нет вовсе, а у программ на Си это .bss; область
     * чистая, потому что инициализированных глобальных у нас не бывает
     * (за этим следит компоновщик, см. user/user.ld).
     */
    if (mmu_map_user(root, USER_BASE, (u64)(uintptr_t)code, code_bytes,
                     MMU_USER_RX) != 0 ||
        mmu_map_user(root, USER_BASE + USER_DATA_OFF, (u64)(uintptr_t)data,
                     USER_DATA_PAGES * PAGE_SIZE, MMU_USER_RW) != 0 ||
        mmu_map_user(root, USER_BASE + USER_STACK_OFF, (u64)(uintptr_t)stack,
                     USER_STACK_PAGES * PAGE_SIZE, MMU_USER_RW) != 0) {
        kprintf("EL0      : %s НЕ ЗАПУЩЕНА — НЕ ВЫШЛО ОТОБРАЗИТЬ\n", name);
        return -1;
    }

    p->entry = USER_BASE;
    /* Стек растёт вниз, поэтому начинаем с верхней границы его страниц */
    p->sp = USER_BASE + USER_STACK_OFF + USER_STACK_PAGES * PAGE_SIZE;

    uspace_stage = 7;                   /* задача */
    t = task_create_space(name, user_trampoline, p, TASK_PRIO_NORMAL, root);
    if (!t) {
        kprintf("EL0      : %s НЕ ЗАПУЩЕНА — НЕТ МЕСТА ПОД ЗАДАЧУ\n", name);
        return -1;
    }

    uspace_stage = 0;                   /* всё, никто не запускается */
    kprintf("EL0      : %s СОЗДАНА, ЗАДАЧА %lu, ПРОСТРАНСТВО %lu\n",
            name, task_id_of(t), root >> 48);
    return (s64)task_id_of(t);
}

/*
 * Список программ, вшитых в образ.
 *
 * Это временная замена файловой системе, и она честно на неё не похожа:
 * список неизменный, номера в нём — часть договора с EL0 (IMG_* в
 * syscall.h). Когда появится чтение разделов, отсюда уедет только
 * источник байтов; всё остальное — отображение, пространство, задача —
 * останется как есть.
 */
static const struct {
    const char *name;
    const u8 *start;
    const u8 *end;
} images[] = {
    { "привет",     user_hello_start, user_hello_end },
    { "нарушитель", user_rogue_start, user_rogue_end },
    { "счёт",       user_spin_start,  user_spin_end  },
    { "двойник",    user_twin_start,  user_twin_end  },
    { "разовая",    user_once_start,  user_once_end  },
    { "запускала",  user_boss_start,  user_boss_end  },
    { "художник",   user_paint_start, user_paint_end },
    { "следопыт",   user_track_start, user_track_end },
    { "панель",     user_panel_start, user_panel_end },
    { "привет-си",  user_hello_c_start, user_hello_c_end },
    { "оболочка",   user_shell_start, user_shell_end },
    { "hittis",     user_vmapp_start, user_vmapp_end },
};

s64 uspace_spawn_image(u32 index)
{
    if (index >= ARRAY_SIZE(images))
        return -1;

    return uspace_spawn(images[index].name, images[index].start,
                        (u64)(images[index].end - images[index].start));
}
