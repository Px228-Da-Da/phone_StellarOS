/*
 * uspace.c — как программа попадает в пользовательский режим.
 *
 * Порядок такой:
 *   1. завести программе своё адресное пространство;
 *   2. взять страницы под код и стек у постраничного аллокатора;
 *   3. скопировать в них программу и согласовать кэши — иначе процессор
 *      выберет из памяти то, что лежало там до копирования;
 *   4. отобразить эти страницы в её пространстве с правами для EL0:
 *      код — читать и исполнять, стек — читать и писать;
 *   5. завести задачу планировщика, которая первым же делом уйдёт в EL0
 *      и больше оттуда не вернётся.
 *
 * Пятый шаг объясняет, почему процесс здесь — это задача планировщика, а
 * не что-то отдельное. У программы в EL0 всё равно должен быть стек в
 * EL1: на него процессор складывает кадр при каждом системном вызове и
 * каждом прерывании. Этот стек — и есть стек задачи, а планировщику при
 * переключении неважно, где задача находилась, в ядре или в программе:
 * он видит только сохранённый указатель стека и номер пространства.
 *
 * Чего здесь ещё нет: освобождения. Страницы завершившейся программы и
 * её таблицы остаются занятыми. Сборщик появится вместе с ожиданием
 * завершения — сейчас освобождать их некому и незачем, программы
 * запускаются один раз при старте.
 */
#include "uspace.h"
#include "mmu.h"
#include "pmm.h"
#include "sched.h"
#include "kmalloc.h"
#include "string.h"
#include "print.h"

/* Спуск в EL0, switch.S */
extern void enter_el0(u64 pc, u64 sp);

/*
 * Где живут программы.
 *
 * Адрес ОДИН И ТОТ ЖЕ для всех: пространства раздельные, и одинаковый
 * виртуальный адрес у двух программ означает разные страницы памяти.
 * Так устроены все настоящие системы, и так же устроена проверка этой
 * раздельности — двойник, запущенный дважды, пишет по одному адресу и
 * не видит соседа.
 *
 * Почему не с нуля, как принято. Ядро отображено единично: виртуальный
 * адрес равен физическому, поэтому вся нижняя часть пространства занята
 * периферией и памятью, и эти отображения есть в каждом пространстве —
 * без них некуда было бы возвращаться из прерывания. Берём заведомо
 * пустой кусок повыше: 64 ГБ при верхней границе в 512.
 */
#define USER_BASE       0x0000001000000000UL
#define USER_STACK_OFF  0x0000000000100000UL    /* стек в мегабайте от кода */
#define USER_STACK_PAGES 2

struct uproc {
    u64 entry;      /* с какого адреса начинать         */
    u64 sp;         /* вершина пользовательского стека  */
};

/*
 * Точка входа задачи. Всё, что здесь происходит в EL1, — это одна
 * строка отчёта; дальше начинается пользовательский режим.
 */
static void user_trampoline(void *arg)
{
    struct uproc *p = arg;

    kprintf("EL0      : %s ПОШЛА, ВХОД %p, СТЕК %p\n",
            task_name(), (void *)(uintptr_t)p->entry,
            (void *)(uintptr_t)p->sp);

    enter_el0(p->entry, p->sp);
}

int uspace_spawn(const char *name, const void *image, u64 size)
{
    struct uproc *p;
    void *code, *stack;
    u64 root, code_bytes;
    u32 code_pages;

    if (!size)
        return -1;

    code_pages = (u32)((size + PAGE_SIZE - 1) / PAGE_SIZE);
    code_bytes = (u64)code_pages * PAGE_SIZE;

    p = kzalloc(sizeof(*p));
    if (!p)
        return -1;

    root = mmu_new_user_space();
    if (!root) {
        kprintf("EL0      : %s НЕ ЗАПУЩЕНА — НЕТ ПРОСТРАНСТВА\n", name);
        return -1;
    }

    code  = pmm_alloc_pages(code_pages);
    stack = pmm_alloc_pages(USER_STACK_PAGES);
    if (!code || !stack) {
        kprintf("EL0      : %s НЕ ЗАПУЩЕНА — НЕТ ПАМЯТИ\n", name);
        return -1;
    }

    memcpy(code, image, size);

    /*
     * Программу мы только что записали как данные, а исполняться она
     * будет через кэш инструкций. Согласовать их обязательно, и именно
     * по ядерному адресу: по пользовательскому трансляции ещё нет, да и
     * действует она только в чужом пространстве.
     */
    mmu_sync_icache((u64)(uintptr_t)code, code_bytes);

    if (mmu_map_user(root, USER_BASE, (u64)(uintptr_t)code, code_bytes,
                     MMU_USER_RX) != 0 ||
        mmu_map_user(root, USER_BASE + USER_STACK_OFF, (u64)(uintptr_t)stack,
                     USER_STACK_PAGES * PAGE_SIZE, MMU_USER_RW) != 0) {
        kprintf("EL0      : %s НЕ ЗАПУЩЕНА — НЕ ВЫШЛО ОТОБРАЗИТЬ\n", name);
        return -1;
    }

    p->entry = USER_BASE;
    /* Стек растёт вниз, поэтому начинаем с верхней границы его страниц */
    p->sp = USER_BASE + USER_STACK_OFF + USER_STACK_PAGES * PAGE_SIZE;

    if (!task_create_space(name, user_trampoline, p, TASK_PRIO_NORMAL, root)) {
        kprintf("EL0      : %s НЕ ЗАПУЩЕНА — НЕТ МЕСТА ПОД ЗАДАЧУ\n", name);
        return -1;
    }

    kprintf("EL0      : %s СОЗДАНА, ПРОСТРАНСТВО %lu, КОД %p\n",
            name, root >> 48, code);
    return 0;
}
