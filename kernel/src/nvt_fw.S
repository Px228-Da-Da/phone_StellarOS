/*
 * Прошивка тачскрина, вшитая прямо в образ ядра.
 *
 * NT36672A не имеет собственной флеш-памяти: прошивку в него заливает
 * хост при каждом включении. Файловой системы у нас пока нет, поэтому
 * файл кладём в образ.
 *
 * Откуда взят: /vendor/firmware/novatek_ts_fw.bin с самого телефона —
 * точнее, его копия из открытого дампа vendor-раздела merlin, потому что
 * SELinux не даёт прочитать оригинал из-под adb. Проверки, что файл тот
 * самый: разбор заголовка (ILM 0xEA53, DLM 0x97, метка "NVT" на 0x1B000,
 * версия 0x1D и её дополнение 0xE2 в сумме дают 0xFF) и аппаратная
 * проверка контрольных сумм самим контроллером после заливки.
 */
        .section .rodata
        .balign 4
        .global nvt_fw
nvt_fw:
        .incbin "../prebuilt/firmware/novatek_ts_fw.bin"
nvt_fw_end:

        .global nvt_fw_size
        .balign 4
nvt_fw_size:
        .word   nvt_fw_end - nvt_fw
