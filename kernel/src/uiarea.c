#define COL_BAR     0xFF05070E      /* полосы темнее рабочей области */
#define COL_TEXT    0xFF9FB4D8
#define COL_DIM     0xFF4A5A7A
#define COL_HOME    0xFF7F8DA8

void ui_area(u32 *x, u32 *y, u32 *w, u32 *h)
{
    u64 base;
    u32 sw, sh, stride;

    trace(TR_STRIP, 0);
    fb_info(&base, &sw, &sh, &stride);

    if (x)
        *x = 0;
    if (y)
        *y = UI_STATUS_H;
    if (w)
        *w = sw;
    if (h)
        *h = (sh > UI_STATUS_H + UI_HOME_H) ? sh - UI_STATUS_H - UI_HOME_H : sh;
}

/* Число в строку: своё, потому что взять негде */
static u32 num(char *dst, u64 v)
{
    char tmp[24];
    u32 n = 0, i = 0;

    do {
        tmp[n++] = (char)('0' + v % 10);
        v /= 10;
    } while (v);

    while (n)
        dst[i++] = tmp[--n];
    dst[i] = 0;
    return i;
}

/*
 * Поле для надписи: собирается в стороне и переносится в кадр целиком.
 *
 * Так лечится последнее мигание. Вывод текста с непрозрачным фоном сам
 * по себе двухходовый: сначала закрашивает всю строку, потом рисует
 * буквы. В окне это незаметно — там рисуют в невидимую половину, — а
 * полосы живут прямо в кадре, который панель читает непрерывно, и она
 * успевает показать закрашенную пустую строку. Именно это и мигало.
 *
 * Поэтому надпись собирается здесь, в обычной памяти, а в кадр уходит
 * одним проходом: каждый пиксель кадра меняется ровно один раз.
 */
/*
 * Разметка панели состояния. Числа обмерены по макету и переведены на
 * наши 1080 точек ширины.
 *
 * Пилюля накрывает вырез камеры: у merlin он в левом верхнем углу,
 * примерно от 35-й до 110-й строки, поэтому пилюля начинается выше и
 * кончается ниже него.
 */
#define PILL_X      24
#define PILL_Y      14
#define PILL_W      306
#define PILL_H      100

#define PLATE_W     300
#define PLATE_H     84
#define PLATE_Y     22
#define PLATE_R     26
#define PLATE_R2    24      /* отступ плашки от правого края */
#define PLATE_GLASS 56      /* доля белого в стекле плашки    */

/* Полоска «домой»: обмерена по макету и переведена на 1080 точек */
#define HOME_W      280
#define HOME_H      14

#define FIELD_W     520
#define FIELD_H     88      /* хватает под значок батареи */

static u32 field[FIELD_W * FIELD_H];

/* Доля покрытия угла: та же четверть точки, что и в оболочке */
static u32 corner_a(int px, int py, int r)
{
    u32 inside = 0;

    for (int sy = 0; sy < 4; sy++)
        for (int sx = 0; sx < 4; sx++) {
            int dx = px * 8 + sx * 2 + 1;
            int dy = py * 8 + sy * 2 + 1;
            int rr = r * 8;

            if (dx * dx + dy * dy <= rr * rr)
                inside++;
        }
    return inside;
}

/*
 * Чем закрашивать полосы: обоями или сплошным цветом.
 *
 * Решает оболочка, а не ядро, и по той же причине, по которой она решает
 * когда гасить экран: это вопрос вида, а не устройства. На замке обои
 * должны идти сквозь полосы, иначе картинка режется чёрным поперёк
 * верха. На тёмном рабочем столе ровно наоборот — светлая лента поверх
 * него выглядит поломкой.
 */
static int strip_wall = 1;      /* сначала показывается замок */

/*
 * Насколько поднято содержимое полосы вслед за пальцем.
 *
 * Ноль в обычной жизни; при жесте разблокировки оболочка сообщает,
 * сколько утянули, и значок заряда уезжает вверх вместе с экраном.
 * Уезжает ЗА край полосы и пропадает — так и надо: в телефоне он уходит
 * вместе со всем содержимым замка.
 */
static u32 strip_up;


/*
 * Значок батареи в поле состояния.
 *
 * Чертёж тот же, что и у крупной батареи в панели управления —
 * inons/stellar_battery.svg, viewBox 256x320: колпачок сверху, корпус,
 * тёмное окно и уровень внутри. Числа ниже — единицы этого чертежа, и
 * переводятся в точки макросом B().
 *
 * Рисуем ПРЯМО В ПОЛЕ, а не отдельной фигурой поверх кадра. Иначе
 * повторилась бы та же беда, что и с плашкой: поле переписывается
 * каждую секунду и стёрло бы значок собой.
 */
#define BATT_UNITS  320
#define BATT_H      76          /* высота значка в точках */

/* Скруглённый прямоугольник внутри поля, со сглаженными углами */
static void field_rrect(int x, int y, int w, int h, int r, u32 color)
{
    for (int row = 0; row < h; row++) {
        int yy = y + row;

        if (yy < 0 || yy >= FIELD_H)
            continue;
        for (int col = 0; col < w; col++) {
            int xx = x + col;
            u32 cov = 16, p, rr, gg, bb;

            if (xx < 0 || xx >= FIELD_W)
                continue;
            if (col < r && row < r)
                cov = corner_a(r - 1 - col, r - 1 - row, r);
            else if (col >= w - r && row < r)
                cov = corner_a(col - (w - r), r - 1 - row, r);
            else if (col < r && row >= h - r)
                cov = corner_a(r - 1 - col, row - (h - r), r);
            else if (col >= w - r && row >= h - r)
                cov = corner_a(col - (w - r), row - (h - r), r);
            if (!cov)
                continue;

            p = field[(u64)yy * FIELD_W + xx];
            rr = (p >> 16 & 0xFF) + ((int)(color >> 16 & 0xFF) - (int)(p >> 16 & 0xFF)) * (int)cov / 16;
            gg = (p >>  8 & 0xFF) + ((int)(color >>  8 & 0xFF) - (int)(p >>  8 & 0xFF)) * (int)cov / 16;
            bb = (p       & 0xFF) + ((int)(color       & 0xFF) - (int)(p       & 0xFF)) * (int)cov / 16;
            field[(u64)yy * FIELD_W + xx] =
                0xFF000000u | (rr << 16) | (gg << 8) | bb;
        }
    }
}

static void field_battery(u32 w, u32 percent)
{
#define B(v)    ((int)(((int)(v) * BATT_H + BATT_UNITS / 2) / BATT_UNITS))
    int bw = 256 * BATT_H / BATT_UNITS;
    int x = (int)w - bw - 12;           /* у правого края поля */
    int y = (FIELD_H - BATT_H) / 2;
    int lo, hi, fill;

    if (percent > 100)
        percent = 100;

    /*
     * Цвета из самого чертежа, а не с фотографии.
     *
     * Первый раз я нарисовал корпус белым — и значок вышел светлым
     * пятном, ни на что не похожим. В stellar_battery.svg наоборот:
     * корпус и колпачок серо-синие (градиент 8a8fa4 → 505468 → 777c91,
     * берём середину), окно почти чёрное 151725, и только уровень
     * белый. Тёмный корпус и есть то, что делает значок узнаваемым.
     */
    field_rrect(x + B(101), y + B(18), B(54), B(26), B(13), 0xFF5A5E73);
    field_rrect(x + B(54), y + B(44), B(148), B(246), B(38), 0xFF5A5E73);
    field_rrect(x + B(74), y + B(66), B(108), B(202), B(25), 0xFF151725);

    /* Уровень: низ на 261, полная высота 188 — как в чертеже */
    lo = y + B(261);
    hi = lo - (int)((u32)B(188) * percent / 100);
    fill = lo - hi;
    if (fill > 0)
        field_rrect(x + B(77), hi, B(102), fill, B(19), 0xFFF7F7F9);
#undef B
}

/*
 * Надпись в полосе состояния.
 *
 * Собираем её в стороне и переносим одним проходом: панель читает кадр
 * непрерывно, и двухходовка «стереть, потом написать» ей видна миганием.
 *
 * Фон под надписью берём ИЗ ОБОЕВ, а не заливаем цветом. Заливка была
 * верной, пока полосы были чёрными; поверх обоев она оставляла тёмный
 * прямоугольник вокруг цифр.
 *
 * И тень: верх этих обоев почти белый, а надпись светлая — без тени она
 * там пропадает ровно так же, как пропали часы на замке.
 */
static void draw_field(u32 x, u32 y, u32 w, const char *s, u32 fg,
                       u32 glass, int batt)
{
    u32 ww = 0, wh = 0;
    const u32 *wall = strip_wall ? wall_pixels(&ww, &wh) : 0;

    if (w > FIELD_W)
        w = FIELD_W;

    if (wall && ww >= x + w && wh >= y + FIELD_H) {
        for (u32 row = 0; row < FIELD_H; row++)
            memcpy(field + (u64)row * FIELD_W,
                   wall + (u64)(y + row) * ww + x, (u64)w * 4);
    } else {
        for (u32 i = 0; i < FIELD_W * FIELD_H; i++)
            field[i] = COL_BAR;
    }

    /*
     * Стекло подмешиваем ЗДЕСЬ, а не полагаемся на нарисованную плашку.
     *
     * Плашка кладётся один раз, а это поле переписывается каждую секунду
     * и берёт фон из чистых обоев — то есть переносом пробивало стекло
     * насквозь, и внутри плашки был виден прямоугольник обоев. Снаружи
     * это выглядело как тёмная рамка вокруг числа.
     *
     * Правильно, чтобы поле собирало под собой всё, что должно быть под
     * ним: сначала обои, потом стекло, потом уже знаки.
     */
    if (glass) {
        for (u32 row = 0; row < FIELD_H; row++)
            for (u32 col = 0; col < w; col++) {
                u32 p = field[(u64)row * FIELD_W + col];
                u32 r = (p >> 16 & 0xFF) + (255 - (p >> 16 & 0xFF)) * glass / 255;
                u32 g = (p >>  8 & 0xFF) + (255 - (p >>  8 & 0xFF)) * glass / 255;
                u32 b = (p       & 0xFF) + (255 - (p       & 0xFF)) * glass / 255;

                field[(u64)row * FIELD_W + col] =
                    0xFF000000u | (r << 16) | (g << 8) | b;
            }
    }

    /*
     * Кегль 3, а не 2: шестнадцать точек против макета слишком мелко.
     *
     * Когда рядом значок, число ставим ВПЛОТНУЮ слева от него, а не по
     * левому краю поля. Иначе процент и значок разъезжаются по разным
     * концам широкого поля и перестают читаться как одно целое — а это
     * одно сведение, а не два.
     */
    {
        u32 tw = fb_text_width(3, s);
        u32 bw = (u32)(256 * BATT_H / BATT_UNITS);
        u32 tx = 8;
        u32 ty = (FIELD_H > 3 * 8 + 8) ? (FIELD_H - 3 * 8) / 2 : 0;

        if (batt >= 0) {
            u32 group = tw + 16 + bw + 12;

            tx = (w > group) ? w - group : 0;
        }
        fb_text_to(field, FIELD_W, w, FIELD_H, tx, ty, 3, fg, 0, s);
    }
    if (batt >= 0)
        field_battery(w, (u32)batt);
    fb_blit(x, y, w, FIELD_H, field, FIELD_W);
}


/* --- Фигуры полосы состояния ----------------------------------------- */

/*
 * Скруглённый прямоугольник поверх обоев.
 *
 * Строим строку в стороне и переносим её одним проходом: панель читает
 * кадр непрерывно, и двухходовка «стереть, потом нарисовать» ей видна.
 * Строка одна на всю ширину экрана — четыре килобайта, не жалко.
 *
 * alpha 255 — сплошная заливка (чёрная пилюля вокруг выреза камеры),
 * меньше — стекло (плашка со значками). Смешиваем с ОБОЯМИ, а не с
 * кадром: кадр в этом месте мы же и рисуем, и читать его обратно из
 * некэшируемой памяти дороже, чем взять исходную точку.
 */
#define ROW_MAX 1600

static u32 row_buf[ROW_MAX];

static void strip_rrect(u32 x, u32 y, u32 w, u32 h, u32 r,
                        u32 color, u32 alpha)
{
    u32 ww = 0, wh = 0;
    const u32 *wall = wall_pixels(&ww, &wh);

    if (!w || !h || w > ROW_MAX)
        return;
    if (r > w / 2)
        r = w / 2;
    if (r > h / 2)
        r = h / 2;

    for (u32 row = 0; row < h; row++) {
        for (u32 col = 0; col < w; col++) {
            u32 cov = 16, k, p, rr, gg, bb;

            if (col < r && row < r)
                cov = corner_a((int)(r - 1 - col), (int)(r - 1 - row), (int)r);
            else if (col >= w - r && row < r)
                cov = corner_a((int)(col - (w - r)), (int)(r - 1 - row), (int)r);
            else if (col < r && row >= h - r)
                cov = corner_a((int)(r - 1 - col), (int)(row - (h - r)), (int)r);
            else if (col >= w - r && row >= h - r)
                cov = corner_a((int)(col - (w - r)), (int)(row - (h - r)), (int)r);

            p = (wall && x + col < ww && y + row < wh)
                ? wall[(u64)(y + row) * ww + x + col] : COL_BAR;

            k = alpha * cov / 16;
            rr = (p >> 16 & 0xFF) + ((int)(color >> 16 & 0xFF) - (int)(p >> 16 & 0xFF)) * (int)k / 255;
            gg = (p >>  8 & 0xFF) + ((int)(color >>  8 & 0xFF) - (int)(p >>  8 & 0xFF)) * (int)k / 255;
            bb = (p       & 0xFF) + ((int)(color       & 0xFF) - (int)(p       & 0xFF)) * (int)k / 255;
            row_buf[col] = 0xFF000000u | (rr << 16) | (gg << 8) | bb;
        }
        fb_blit(x, y + row, w, 1, row_buf, w);
    }
}

/*
 * Полосы уже нарисованы: дальше меняется только текст.
 *
 * Фон под полосами кладётся однажды — закрашивать их на каждом
 * обновлении значит мигать по той же причине, что описана выше.
 */
static int bars_painted;

/*
 * Поднять содержимое полосы. Перерисовывает сразу: жест идёт шестьдесят
 * раз в секунду, ждать общего обновления раз в секунду тут нельзя.
 */
void ui_strip_lift(u32 px)
{
    if (px > UI_STATUS_H)
        px = UI_STATUS_H;
    if (px == strip_up)
        return;
    strip_up = px;
    ui_status_draw();
}

void ui_strip_wallpaper(int on)
{
    if (!!on == strip_wall)
        return;
    strip_wall = !!on;
    ui_status_repaint();
}

void ui_status_repaint(void)
{
    bars_painted = 0;
    ui_status_draw();
}

void ui_status_draw(void)
{
    /* отметка ниже, после проверок */
    u64 base;
    u32 sw, sh, stride;
    char line[64];
    u32 n;
    struct battery_state bat;

    if (!fb_available())
        return;

    fb_info(&base, &sw, &sh, &stride);
    if (sh <= UI_STATUS_H + UI_HOME_H)
        return;

    if (!bars_painted) {
        u32 bar_w = HOME_W;
        u32 bar_x = (sw - bar_w) / 2;
        u32 bar_y = sh - UI_HOME_H / 2 - HOME_H / 2;
        u32 ww = 0, wh = 0;
        const u32 *wall = wall_pixels(&ww, &wh);

        fb_strip_mine(1);
        /*
         * Под полосы кладём ОБОИ, а не сплошной цвет.
         *
         * Окно программы начинается ниже полосы состояния, поэтому
         * закрашенная полоса резала картинку чёрным поперёк верха, и
         * экран переставал выглядеть цельным. Обои у ядра уже есть
         * готовые, во весь экран, — берём из них ровно те строки, что
         * приходятся на полосы, и картинка сходится встык.
         */
        if (strip_wall && wall && ww == sw && wh == sh) {
            fb_blit(0, 0, sw, UI_STATUS_H, wall, sw);
            fb_blit(0, sh - UI_HOME_H, sw, UI_HOME_H,
                    wall + (u64)(sh - UI_HOME_H) * sw, sw);
        } else {
            fb_fill_rect(0, 0, sw, UI_STATUS_H, COL_BAR);
            fb_fill_rect(0, sh - UI_HOME_H, sw, UI_HOME_H, COL_BAR);
        }
        /*
         * Полоска «домой» по макету: белая, со скруглёнными концами.
         *
         * Было шесть точек серо-синего прямоугольника с острыми углами —
         * заметно тоньше и тусклее образца. Теперь за неё ещё и тянут,
         * значит она должна выглядеть тем, за что можно взяться.
         */
        strip_rrect(bar_x, bar_y, bar_w, HOME_H, HOME_H / 2,
                    0xFFFFFFFFu, 235);

        /*
         * Панель состояния по макету: чёрная «пилюля» у выреза камеры и
         * скруглённая полупрозрачная плашка справа под значки.
         *
         * Пилюля непрозрачная и чёрная нарочно: вырез камеры и сам
         * чёрный, и пилюля с ним сливается — получается один сплошной
         * остров, как в образце, а не дырка посреди картинки.
         *
         * Плашка стеклянная: под ней обои, а обои у нас плавные, поэтому
         * размытие им ничего не добавит — хватает подмешать белого.
         */
        if (strip_wall && wall && ww == sw && wh == sh) {
            strip_rrect(PILL_X, PILL_Y, PILL_W, PILL_H, PILL_H / 2,
                        0xFF000000u, 255);
            /*
             * Плашки под значком нет: в ней не было нужды, а стекло на
             * светлых обоях само по себе почти не читается — выходило
             * блёклое пятно вокруг числа.
             */
        }

        fb_strip_mine(0);
        bars_painted = 1;
    }


    /*
     * Часы слева, но не под вырезом камеры: у merlin он в левом верхнем
     * углу, и надпись под ним просто не видна.
     */
    /*
     * Время суток, а не время работы.
     *
     * Раньше здесь стояли минуты и секунды с включения — годилось, пока
     * это была отладочная строка. Теперь это единственные часы, которые
     * телефон показывает всегда: и на рабочем столе, и в приложении, и
     * на замке. Часам полагается показывать время.
     */
    /*
     * Часов в полосе больше нет.
     *
     * Они там были ещё с той поры, когда полоса была отладочной строкой,
     * и на экране блокировки просто спорили с крупными часами посреди
     * него. В макете верхняя панель несёт только состояние устройства.
     *
     * Побочная польза: пропал поход к контроллеру времени раз в секунду,
     * а это семь обращений по шине питания — той самой, за которую
     * борются ещё и опрос кнопки, и замер заряда.
     */


    /* --- заряд --- */
    battery_last(&bat);
    n = 0;
    if (bat.valid) {
        n += num(line + n, bat.percent);
        line[n++] = '%';

        /*
         * Ток рядом с процентом больше не пишем.
         *
         * Он честнее всего показывает происходящее — минус значит
         * разряжается, плюс заряжается, — но в макете справа только
         * значки, а «+302 mA» это отладочное число, и на экране
         * блокировки ему не место. Потери сведений нет: пульс печатает
         * его в консоль каждую секунду, вместе с напряжением и
         * напряжением без нагрузки.
         *
         * Заряжается или нет, видно и без числа: при зарядке процент
         * растёт, а значок в панели управления зеленеет.
         */
        line[n] = 0;
    } else if (timer_uptime_ms() > 5000) {
        /*
         * Про батарею спрашиваем вслух только когда молчание уже
         * странное. Первые секунды замера просто ещё нет — счётчик
         * заряда поднимается не мгновенно, — и кричать об этом на весь
         * экран значит пугать человека нормальным ходом загрузки.
         */
        const char *q = "БАТАРЕЯ?";

        while (*q)
            line[n++] = *q++;
        line[n] = 0;
    } else {
        line[0] = 0;
    }

    /*
     * Заряд — ВНУТРИ стеклянной плашки справа, с отступом от её края.
     *
     * Ток при этом убран: в макете справа только значки, а «+302 mA» —
     * отладочное число, которому там не место. Оно никуда не делось, его
     * печатает пульс в консоль каждую секунду.
     */
    {
        u32 w = PLATE_W - 32;
        u32 x = (sw > PLATE_W + PLATE_R2) ? sw - PLATE_W - PLATE_R2 + 16 : 0;
        u32 base_y = PLATE_Y + (PLATE_H - FIELD_H) / 2;
        u32 yy = (base_y > strip_up) ? base_y - strip_up : 0;

        /*
         * Прежнее место возвращаем к обоям ДО того, как нарисуем на
         * новом. Поле собирает свой фон само, но только под собой: без
         * этого за уезжающим значком тянулся бы след.
         */
        {
            static u32 was_y;
            u32 ww = 0, wh = 0;
            const u32 *wall = strip_wall ? wall_pixels(&ww, &wh) : 0;

            if (wall && was_y != yy && was_y + FIELD_H <= wh)
                fb_blit(x, was_y, w, FIELD_H,
                        wall + (u64)was_y * ww + x, ww);
            was_y = yy;
        }

        draw_field(x, yy, w, line,
                   bat.valid && bat.percent < 15 ? 0xFFFF6B6B : 0xFFFFFFFF,
                   0, bat.valid ? (int)bat.percent : -1);
    }

    (void)COL_DIM;
}

static void ui_status_task(void *arg)
{
    u32 n = 0;

    (void)arg;

    for (;;) {
        ui_status_draw();

        /*
         * Первые секунды перерисовываем чаще.
         *
         * В кадр при загрузке пишет не только эта задача, и если полосы
         * кто-то затрёт, ждать целую секунду до починки — значит показать
         * человеку пустой верх экрана ровно в тот момент, когда он на
         * него смотрит. Дальше в кадре никто не хозяйничает, и раз в
         * секунду хватает: там только часы и заряд.
         */
        task_sleep_ms(n < 20 ? 250 : 1000);
        n++;
    }
}

void ui_status_start(void)
{
    task_create("полосы", ui_status_task, NULL);
}
