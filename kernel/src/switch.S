/*
 * switch.S — переключение контекста задач.
 *
 * Сохраняем только callee-saved регистры x19..x28, кадровый указатель x29
 * и адрес возврата x30. Всё остальное по соглашению AArch64 и так считается
 * испорченным после вызова функции, а переключение — это всегда вызов
 * ctx_switch из Си-кода.
 *
 * Кадр из 12 регистров = 96 байт, кратно 16 — требование к выравниванию SP.
 */

.section ".text", "ax"

/*
 * void ctx_switch(u64 *save_sp, u64 new_sp);
 *
 * x0 — куда записать SP уходящей задачи
 * x1 — SP задачи, на которую переключаемся
 */
.global ctx_switch
ctx_switch:
    sub     sp, sp, #96
    stp     x19, x20, [sp, #0]
    stp     x21, x22, [sp, #16]
    stp     x23, x24, [sp, #32]
    stp     x25, x26, [sp, #48]
    stp     x27, x28, [sp, #64]
    stp     x29, x30, [sp, #80]

    mov     x9, sp
    str     x9, [x0]            /* уходящая задача запомнила свой стек */
    mov     sp, x1              /* с этой инструкции мы уже в чужом стеке */

    ldp     x19, x20, [sp, #0]
    ldp     x21, x22, [sp, #16]
    ldp     x23, x24, [sp, #32]
    ldp     x25, x26, [sp, #48]
    ldp     x27, x28, [sp, #64]
    ldp     x29, x30, [sp, #80]
    add     sp, sp, #96

    /* ret уводит нас туда, где эта задача когда-то вызвала ctx_switch,
     * а для новорождённой — в task_start: её x30 подготовлен вручную. */
    ret

/*
 * Точка входа новой задачи.
 *
 * Обычная задача возвращается из ctx_switch в середину schedule(), где
 * блокировка очереди будет снята. Новорождённой возвращаться некуда,
 * поэтому она снимает блокировку сама — иначе первое же переключение
 * оставило бы очередь готовых задач захваченной навсегда.
 *
 * x19 — функция задачи, x20 — её аргумент: положены в кадр при создании.
 */
.global task_start
task_start:
    bl      sched_after_switch
    msr     daifclr, #2         /* задача обязана исполняться с прерываниями */
    mov     x0, x20
    blr     x19
    bl      task_exit
1:  wfe                         /* task_exit не возвращается, но подстрахуемся */
    b       1b
