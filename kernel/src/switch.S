/*
 * switch.S — переключение контекста задач.
 *
 * Сохраняем только callee-saved регистры x19..x28, кадровый указатель x29
 * и адрес возврата x30. Всё остальное по соглашению AArch64 и так считается
 * испорченным после вызова функции, а переключение — это всегда вызов
 * ctx_switch из Си-кода.
 *
 * Кадр из 12 регистров = 96 байт, кратно 16 — требование к выравниванию SP.
 */

.section ".text", "ax"

/*
 * void ctx_switch(u64 *save_sp, u64 new_sp);
 *
 * x0 — куда записать SP уходящей задачи
 * x1 — SP задачи, на которую переключаемся
 */
.global ctx_switch
ctx_switch:
    sub     sp, sp, #96
    stp     x19, x20, [sp, #0]
    stp     x21, x22, [sp, #16]
    stp     x23, x24, [sp, #32]
    stp     x25, x26, [sp, #48]
    stp     x27, x28, [sp, #64]
    stp     x29, x30, [sp, #80]

    mov     x9, sp
    str     x9, [x0]            /* уходящая задача запомнила свой стек */
    mov     sp, x1              /* с этой инструкции мы уже в чужом стеке */

    ldp     x19, x20, [sp, #0]
    ldp     x21, x22, [sp, #16]
    ldp     x23, x24, [sp, #32]
    ldp     x25, x26, [sp, #48]
    ldp     x27, x28, [sp, #64]
    ldp     x29, x30, [sp, #80]
    add     sp, sp, #96

    /* ret уводит нас туда, где эта задача когда-то вызвала ctx_switch,
     * а для новорождённой — в task_start: её x30 подготовлен вручную. */
    ret

/*
 * Точка входа новой задачи.
 *
 * Обычная задача возвращается из ctx_switch в середину schedule(), где
 * блокировка очереди будет снята. Новорождённой возвращаться некуда,
 * поэтому она снимает блокировку сама — иначе первое же переключение
 * оставило бы очередь готовых задач захваченной навсегда.
 *
 * x19 — функция задачи, x20 — её аргумент: положены в кадр при создании.
 */
.global task_start
task_start:
    bl      sched_after_switch
    msr     daifclr, #2         /* задача обязана исполняться с прерываниями */
    mov     x0, x20
    blr     x19
    bl      task_exit
1:  wfe                         /* task_exit не возвращается, но подстрахуемся */
    b       1b

/*
 * void enter_el0(u64 pc, u64 sp);
 *
 * Спуск в пользовательский режим. Обратной дороги у этой функции нет:
 * eret уводит процессор в EL0, и вернуться оттуда можно только через
 * исключение — системный вызов, прерывание или ошибку.
 *
 * Три регистра описывают, куда именно мы уходим:
 *   ELR_EL1   с какой команды продолжить
 *   SPSR_EL1  в каком состоянии: ноль означает EL0t (свой стек SP_EL0)
 *             и разрешённые прерывания — без них программа не вытеснялась
 *             бы по таймеру и заняла бы ядро целиком
 *   SP_EL0    стек программы
 *
 * Остальные регистры обнуляем. Это не украшение: в них лежат адреса
 * ядерных структур, оставшиеся от вызывающего, и отдавать их программе,
 * от которой мы только что закрыли всю память, было бы странно.
 */
.global enter_el0
enter_el0:
    msr     sp_el0, x1
    msr     elr_el1, x0
    mov     x2, #0
    msr     spsr_el1, x2

    mov     x0,  #0
    mov     x1,  #0
    mov     x2,  #0
    mov     x3,  #0
    mov     x4,  #0
    mov     x5,  #0
    mov     x6,  #0
    mov     x7,  #0
    mov     x8,  #0
    mov     x9,  #0
    mov     x10, #0
    mov     x11, #0
    mov     x12, #0
    mov     x13, #0
    mov     x14, #0
    mov     x15, #0
    mov     x16, #0
    mov     x17, #0
    mov     x18, #0
    mov     x19, #0
    mov     x20, #0
    mov     x21, #0
    mov     x22, #0
    mov     x23, #0
    mov     x24, #0
    mov     x25, #0
    mov     x26, #0
    mov     x27, #0
    mov     x28, #0
    mov     x29, #0
    mov     x30, #0
    eret
