/* Где лежит плитка. y — уже с учётом прокрутки */
static void tile_rect(u32 i, int *x, int *y)
{
    *x = (int)(MARGIN + (i % COLS) * (tile_w + GAP));
    *y = (int)list_top + (int)((i / COLS) * (TILE_H + GAP)) - scroll;
}

/* Какая плитка под точкой; -1 — мимо всех */
static int tile_at(u32 px, u32 py)
{
    if (py < list_top || py >= list_bottom)
        return -1;

    for (u32 i = 0; i < TILE_COUNT; i++) {
        int x, y;

        tile_rect(i, &x, &y);
        if ((int)px >= x && (int)px < x + (int)tile_w &&
            (int)py >= y && (int)py < y + TILE_H)
            return (int)i;
    }

    return -1;
}

/* Две кнопки делят ширину плитки поровну, с зазором посередине */
#define BTN_GAP     16

static void btn_rect(int which, u32 *x, u32 *y, u32 *w, u32 *h)
{
    u32 bw = (tile_w > BTN_GAP) ? (tile_w - BTN_GAP) / 2 : tile_w;

    *h = BTN_H;
    *y = (sh > BTN_H + MARGIN) ? sh - BTN_H - MARGIN : HEADER_H;
    *w = bw;
    *x = MARGIN + (which == BTN_OFF ? bw + BTN_GAP : 0);
}

/* Какая кнопка под точкой; -1 — ни одной */
static int btn_at(u32 px, u32 py)
{
    for (int i = 0; i < BTN_COUNT; i++) {
        u32 x, y, w, h;

        btn_rect(i, &x, &y, &w, &h);
        if (px >= x && px < x + w && py >= y && py < y + h)
            return i;
    }
    return -1;
}

/* --- Рисование ------------------------------------------------------ */

/*
 * Прямоугольник, обрезанный по экрану.
 *
 * При прокрутке плитка наполовину уходит под шапку, и рисовать её
 * целиком нельзя — вылезем за буфер окна. Пропускать такую плитку тоже
 * нельзя: она исчезала бы целиком вместо того, чтобы уезжать. Значит
 * рисуем ровно её видимую часть.
 */
static void vrect(int x, int y, int w, int h, u32 color)
{
    int x1 = x + w, y1 = y + h;

    if (x < 0)
        x = 0;
    if (y < 0)
        y = 0;
    if (x1 > (int)sw)
        x1 = (int)sw;
    if (y1 > (int)sh)
        y1 = (int)sh;
    if (x1 <= x || y1 <= y)
        return;

    urect(back, sw, (u32)x, (u32)y, (u32)(x1 - x), (u32)(y1 - y), color);
}

/*
 * Скруглённый прямоугольник со сглаженными углами.
 *
 * Это главный опознавательный знак интерфейса, к которому мы идём: там
 * скруглено всё, и радиусы крупные. Острый угол выдаёт подделку сразу,
 * а ступенчатый — ещё вернее, потому что при радиусе в сорок точек
 * лесенка видна невооружённым глазом.
 *
 * Как считается. Углы — четверти круга. Для каждой строки внутри
 * углового квадрата ищем, с какого столбца начинается тело: точка
 * принадлежит кругу, пока dx*dx + dy*dy <= r*r. Дробных чисел в системе
 * нет вовсе, и они здесь не нужны — всё это целые.
 *
 * Сглаживание. Край круга проходит между точками, и чтобы он не выглядел
 * лесенкой, крайние точки закрашиваются смесью цвета тела и того, что
 * лежит под ним. Долю считаем честно: делим точку на 4x4 и смотрим,
 * сколько из шестнадцати её частей попало внутрь. Это дороже, но только
 * по краю — шестнадцать проб на точку, а таких точек на весь угол
 * десятки.
 *
 * Цвет фона передаётся, а не читается из буфера намеренно. Читать из
 * некэшируемой памяти дорого, а главное — под карточкой у нас всегда
 * известный ровный фон. Когда понадобится класть скруглённое на пёстрое,
 * это станет неверно, и тогда сюда придётся вернуться.
 *
 * Цена. Тело рисуется целыми строками, как обычный прямоугольник, то
 * есть даром. Считаются только четыре угловых квадрата r на r — при
 * радиусе 40 это 6400 точек на карточку, из них с пробами лишь края.
 * Правило «каждый пиксель за кадр меняется один раз» не нарушается:
 * каждая точка по-прежнему пишется ровно однажды.
 */

/* Смешать два цвета: доля a от 0 до 16 берётся у fg, остальное у bg */
static u32 mix16(u32 fg, u32 bg, u32 a)
{
    u32 r = ((fg >> 16 & 0xFF) * a + (bg >> 16 & 0xFF) * (16 - a)) / 16;
    u32 g = ((fg >>  8 & 0xFF) * a + (bg >>  8 & 0xFF) * (16 - a)) / 16;
    u32 b = ((fg       & 0xFF) * a + (bg       & 0xFF) * (16 - a)) / 16;

    return 0xFF000000u | (r << 16) | (g << 8) | b;
}

/*
 * Сколько из шестнадцати частей точки лежит внутри круга радиуса r.
 *
 * Точка (px, py) задана расстоянием её левого верхнего края от центра
 * скругления. Делим на 4x4 и считаем попадания по центрам частей —
 * отсюда шаги в четверть точки, которые взяты в четвертях же, чтобы не
 * заводить дроби: 1, 3, 5, 7 восьмых.
 */
static u32 corner_cover(int px, int py, int r)
{
    u32 inside = 0;

    for (int sy = 0; sy < 4; sy++) {
        for (int sx = 0; sx < 4; sx++) {
            /* центр части в восьмых долях точки */
            int dx = px * 8 + sx * 2 + 1;
            int dy = py * 8 + sy * 2 + 1;
            int rr = r * 8;

            if (dx * dx + dy * dy <= rr * rr)
                inside++;
        }
    }
    return inside;
}

/*
 * Скруглённый прямоугольник.
 *
 * bg — то, что лежит под ним: нужно для сглаживания краёв. Радиус
 * ограничиваем половиной меньшей стороны, иначе углы налезут друг на
 * друга и вместо скругления получится каша.
 */
static void vrrect(int x, int y, int w, int h, int r, u32 color, u32 bg)
{
    int half = (w < h ? w : h) / 2;

    if (r > half)
        r = half;
    if (r <= 0) {
        vrect(x, y, w, h, color);
        return;
    }

    /* Середина по высоте — обычные сплошные строки, во всю ширину */
    vrect(x, y + r, w, h - 2 * r, color);

    /*
     * Углы и полосы между ними. Идём по строкам сверху и снизу
     * одновременно: скругление симметрично, и счёт для строки годится
     * обеим.
     */
    for (int i = 0; i < r; i++) {
        int py = r - 1 - i;         /* расстояние строки от центра скругления */
        int cut = r;                /* с какого столбца начинается сплошное  */

        /* Ищем первый столбец, целиком лежащий внутри */
        while (cut > 0 && corner_cover(r - cut, py, r) == 16)
            cut--;

        /* Сплошная часть строки — одним прямоугольником, как обычно */
        vrect(x + cut, y + i, w - 2 * cut, 1, color);
        vrect(x + cut, y + h - 1 - i, w - 2 * cut, 1, color);

        /*
         * Края: по одной точке, каждая своей смесью.
         *
         * Точки, оказавшиеся совсем снаружи круга, закрашиваются фоном, а
         * НЕ пропускаются. Здесь я сначала ошибся: пропускал их, считая,
         * что снаружи и трогать нечего.
         *
         * Экран в этой системе никогда не заливается целиком — каждая
         * точка пишется ровно один раз за кадр, и это единственный способ
         * уложиться в кадр. Значит пропущенная точка остаётся от кадра
         * прошлого. При прокрутке там лежал кусок плитки с прежнего
         * места, и углы обрастали клиньями.
         *
         * Отсюда правило для всего, что мы будем рисовать дальше: примитив
         * обязан закрасить ВЕСЬ свой прямоугольник, включая то, что
         * считает пустым. Пустого места на экране не бывает.
         */
        for (int c = 0; c < cut; c++) {
            u32 a = corner_cover(r - 1 - c, py, r);
            u32 col = a ? mix16(color, bg, a) : bg;

            vrect(x + c, y + i, 1, 1, col);
            vrect(x + w - 1 - c, y + i, 1, 1, col);
            vrect(x + c, y + h - 1 - i, 1, 1, col);
            vrect(x + w - 1 - c, y + h - 1 - i, 1, 1, col);
        }
    }
}

