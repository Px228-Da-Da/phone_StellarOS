/*
 * Батарея.
 *
 * Нарисована, а не показана картинкой, и это не от лени. Рисунок
 * inons/stellar_battery.svg служит здесь чертежом: из него взяты все
 * пропорции — колпачок, корпус, тёмное окно, отступы жидкости. Но сам
 * он показать заряд не может, потому что уровень в нём задан
 * координатами пути: «Q128 144 179 156» — верх жидкости на 156, то есть
 * навсегда около половины. Любая растеризация заморозила бы его
 * окончательно, а просили ровно обратного.
 *
 * Все числа ниже — единицы того чертежа, viewBox 256x320, и переводятся
 * в точки экрана через S(). Так рисунок и код не разъедутся: поправят
 * SVG — те же числа поправятся здесь.
 *
 * h — высота на экране целиком, вместе с колпачком.
 */
#define BAT_UNITS   320             /* высота чертежа в его единицах */

static u32 bat_low_color(u32 percent, int charging)
{
    if (charging)
        return 0xFF30D158;          /* systemGreen: заряжается        */
    if (percent <= 20)
        return COL_RED;             /* предупреждение, а не украшение */
    return 0xFFF2F3F7;              /* белый из градиента чертежа     */
}

static void draw_battery_bg(int x, int y, int h, u32 percent,
                            int charging, u32 bg)
{
    /* Перевод единиц чертежа в точки экрана */
#define S(v)    ((int)(((int)(v) * h + BAT_UNITS / 2) / BAT_UNITS))

    const u32 frame = 0xFF6A6E83;   /* середина градиента корпуса     */
    const u32 well  = 0xFF151725;   /* тёмное окно, цвет прямо из SVG */
    u32 liquid = bat_low_color(percent, charging);
    int lo, hi, top;

    if (percent > 100)
        percent = 100;

    /* Колпачок и корпус */
    vrrect(x + S(101), y + S(18), S(54), S(26), S(13), frame, bg);
    vrrect(x + S(54), y + S(44), S(148), S(246), S(38), frame, bg);

    /* Тёмное окно поверх корпуса: фон под ним — сам корпус */
    vrrect(x + S(74), y + S(66), S(108), S(202), S(25), well, frame);

    /*
     * Жидкость. Низ на 261, полная высота 188 — это ровно окно за
     * вычетом тех же семи единиц отступа сверху и снизу, что и в
     * чертеже. Пустая батарея не рисуется вовсе: полоска в одну точку
     * читалась бы как «немного есть», а её нет.
     */
    lo = y + S(261);
    hi = lo - (int)((u32)S(188) * percent / 100);
    top = lo - hi;
    if (top > 0)
        vrrect(x + S(77), hi, S(102), top, S(19), liquid, well);

#undef S
}


