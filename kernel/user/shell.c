/*
 * Вырез камеры.
 *
 * У merlin он в левом верхнем углу и заходит в окно программы на
 * несколько десятков точек. Раньше об него уже спотыкались системные
 * часы — надпись под вырезом просто не видна. Держим область занятой и
 * ничего в неё не кладём.
 */
#define CAM_BOTTOM      56          /* докуда вырез достаёт в окне */

static int panel_open;
static int panel_drag;              /* сколько протянули, пока не открылась */

/* Стеклянный скруглённый прямоугольник поверх того, что уже нарисовано */
static void glass_rrect(int x, int y, int w, int h, int r, u32 alpha)
{
    for (int row = 0; row < h; row++) {
        int yy = y + row;
        u32 *line;

        if (yy < 0 || yy >= (int)sh)
            continue;
        line = back + (u64)yy * sw;
        for (int col = 0; col < w; col++) {
            int xx = x + col;
            u32 a = 16, p, k, rr, gg, bb;

            if (xx < 0 || xx >= (int)sw)
                continue;
            /* Доля покрытия у углов — та же, что у плиток */
            if (col < r && row < r)
                a = corner_cover(r - 1 - col, r - 1 - row, r);
            else if (col >= w - r && row < r)
                a = corner_cover(col - (w - r), r - 1 - row, r);
            else if (col < r && row >= h - r)
                a = corner_cover(r - 1 - col, row - (h - r), r);
            else if (col >= w - r && row >= h - r)
                a = corner_cover(col - (w - r), row - (h - r), r);
            if (!a)
                continue;

            p = line[xx];
            k = alpha * a / 16;
            rr = (p >> 16 & 0xFF) + (255 - (p >> 16 & 0xFF)) * k / 255;
            gg = (p >>  8 & 0xFF) + (255 - (p >>  8 & 0xFF)) * k / 255;
            bb = (p       & 0xFF) + (255 - (p       & 0xFF)) * k / 255;
            line[xx] = 0xFF000000u | (rr << 16) | (gg << 8) | bb;
        }
    }
}

/* Где лежит ползунок яркости */
static void bright_box(int *x, int *y, int *w, int *h)
{
    *w = (int)(sw - 2 * MARGIN - 120) / 2;
    *h = 620;
    *x = MARGIN + 60;
    *y = PANEL_TOP + 150;
}

/*
 * Нарисовать панель поверх текущего кадра.
 *
 * Фон под ней уже нарисован тем, кто рисовал кадр: панель только
 * подмешивает белого и кладёт сверху свои надписи. Отдельного фона у неё
 * нет намеренно — сквозь стекло должно быть видно, что под ним.
 */
static void draw_panel(void)
{
    s64 b = battery_now();
    s64 pc = screen_bright_get();
    char line[64];
    int x, y, w, h;
    u32 n;

    glass_rrect(MARGIN, PANEL_TOP, (int)sw - 2 * MARGIN,
                (int)sh - PANEL_TOP - 300, PANEL_R, GLASS_PANEL);

    text(MARGIN + 60, PANEL_TOP + 50, 5, COL_WHITE, 0, "Управление");

    /* --- Яркость: вертикальный ползунок, как в телефоне --- */
    bright_box(&x, &y, &w, &h);
    if (pc < 0) {
        text(x, y, 4, COL_DIM, 0, "Яркость недоступна");
    } else {
        int fill = (int)((u32)h * (u32)pc / 100);

        vrrect(x, y, w, h, w / 2, 0x40FFFFFF, COL_BG);
        glass_rrect(x, y, w, h, w / 2, 40);
        if (fill > 0)
            vrrect(x, y + h - fill, w, fill, w / 2, 0xFFF2F3F7, COL_BG);

        n = unum(line, (u32)pc);
        line[n++] = '%';
        line[n] = 0;
        text((u32)x, (u32)(y + h + 26), 4, COL_WHITE, 0, line);
        text((u32)x, (u32)(y - 44), 4, COL_DIM, 0, "Яркость");
    }

    /* --- Заряд: только показываем, менять нечего --- */
    x = (int)sw / 2 + 30;
    y = PANEL_TOP + 150;
    if (BATT_OK(b)) {
        n = unum(line, BATT_PERCENT(b));
        line[n++] = '%';
        line[n] = 0;
        text((u32)x, (u32)y, 4, COL_DIM, 0, "Батарея");
        text((u32)x, (u32)(y + 60), 6, COL_WHITE, 0, line);
        /* Тот самый значок с чертежа: здесь у него есть место показать
         * уровень крупно, чего в узкой полосе состояния не выходило. */
        draw_battery_on((int)sw - MARGIN - 150, y + 30, 150,
                        BATT_PERCENT(b), (int)BATT_CHARGING(b));

        n = 0;
        if (BATT_CHARGING(b)) {
            const char *p = "Заряжается";

            while (*p)
                line[n++] = *p++;
        } else {
            const char *p = "От батареи";

            while (*p)
                line[n++] = *p++;
        }
        line[n] = 0;
        text((u32)x, (u32)(y + 150), 4, COL_DIM, 0, line);
    }

    text(MARGIN + 60, (int)sh - 360, 4, COL_DIM, 0,
         "Проведите вверх, чтобы закрыть");
}

/*
 * Кадр целиком.
 *
 * Заливки всего окна здесь нет намеренно. Раньше кадр начинался с
 * ufill на 1080x2340 — десять мегабайт записи в некэшируемую память, —
 * а потом плитки закрашивали ту же площадь второй раз. Восемнадцать
 * мегабайт на кадр не укладываются в шестнадцать миллисекунд ни при
 * каком старании, и прокрутка получалась рваной.
 *
 * Теперь каждый пиксель пишется ровно один раз: плитки закрашивают
 * себя, промежутки между ними — отдельные полосы, поля по краям —
 * два столбца. Шапка и нижняя полоса рисуются последними и заодно
 * служат отсечением для уехавших плиток.
 */
static void draw_all(void)
{
    int y = (int)list_top - scroll;
    u32 step = TILE_H + GAP;

    /* Поля слева и справа от списка */
    vrect(0, (int)list_top, MARGIN, (int)(list_bottom - list_top), COL_BG);
    vrect((int)(MARGIN + tile_w), (int)list_top,
          (int)(sw - MARGIN - tile_w), (int)(list_bottom - list_top), COL_BG);

    /* Промежуток над первой плиткой — он появляется на резиновом крае */
    if (y > (int)list_top)
        vrect(MARGIN, (int)list_top, (int)tile_w, y - (int)list_top, COL_BG);

    for (u32 i = 0; i < TILE_COUNT; i++) {
        draw_tile(i);
        /* Промежуток под плиткой */
        vrect(MARGIN, y + TILE_H, (int)tile_w, GAP, COL_BG);
        y += (int)step;
    }

    /* Остаток снизу, если список кончился раньше видимой части */
    if (y < (int)list_bottom)
        vrect(MARGIN, y, (int)tile_w, (int)list_bottom - y, COL_BG);

    draw_scrollbar();

    /* Шапка и полоса — последними, поверх списка: это и есть отсечение */
    draw_header();
    draw_bar();
}

/* --- Прокрутка ------------------------------------------------------ */

/*
 * Куда поставить список.
 *
 * За краями не обрезаем, а пускаем с сопротивлением: палец уводит список
 * втрое слабее, чем внутри, и не дальше ладони. Возвращает его пружина —
 * см. fling_step.
 */
static void scroll_to(int v)
{
    if (v < 0) {
        v /= RUBBER;
        if (v < -RUBBER_MAX)
            v = -RUBBER_MAX;
    } else if (v > scroll_max) {
        v = scroll_max + (v - scroll_max) / RUBBER;
        if (v > scroll_max + RUBBER_MAX)
            v = scroll_max + RUBBER_MAX;
    }
    scroll_want = v;
}

/*
 * Подтянуться к пальцу.
 *
 * Список идёт не прямо в точку последнего замера, а долей пути к ней за
 * кадр. Причина не в красоте: панель опрашивается двести раз в секунду,
 * рисуем мы шестьдесят кадров, и между кадрами набегает то три замера,
 * то четыре. Шаг выходит неровным при идеально ровных кадрах — и именно
 * это глаз читает как дрожь. Доля пути эту неровность съедает, а
 * отставание получается меньше кадра и незаметно.
 *
 * Возвращает 1, если картинка изменилась.
 */
static int follow_finger(void)
{
    int d = scroll_want - scroll;

    if (!d)
        return 0;

    if (d > -2 && d < 2)
        scroll = scroll_want;
    else
        scroll += d * 2 / 3;

    return 1;
}

/* Внутри границ или уже за ними */
static int out_of_bounds(void)
{
    return scroll < 0 || scroll > scroll_max;
}

/* Список сам по себе в движении: летит или возвращается пружиной */
static int scroll_busy(void)
{
    return fling != 0 || out_of_bounds();
}

/*
 * Шаг движения: сначала пружина, потом полёт.
 *
 * Скорость гасим долей за кадр, а не вычитанием: тогда быстрый бросок
 * летит долго, а медленный останавливается сразу — так ведёт себя
 * трение. Возвращает 1, пока картинка меняется.
 */
static int fling_step(void)
{
    u64 now = uptime_ms();
    int dt, edge, d;

    if (!scroll_busy()) {
        step_ms = now;
        frac = 0;
        return 0;
    }

    /*
     * Пока палец на экране — не двигаем ничего сами.
     *
     * У края список уходит в резину, а пружина честно тянула его
     * обратно прямо под пальцем: держишь, а он ползёт. Список слушается
     * либо пальца, либо себя, но не обоих сразу.
     */
    if (touching) {
        step_ms = now;
        frac = 0;
        return 0;
    }

    dt = step_ms ? (int)(now - step_ms) : FRAME_MS;
    step_ms = now;
    if (dt < 1)
        dt = 1;
    if (dt > 64)                /* проспали дольше — не прыгаем через пол-экрана */
        dt = 64;

    /*
     * Пружина сильнее полёта: за краем список только возвращается.
     *
     * Цель пальца обновляем ПОСЛЕ каждого шага, а не до. Сначала было до
     * — и список после первого же отскока начинал дёргаться на месте
     * навсегда: пружина тянула его к краю, а подтягивание к пальцу
     * возвращало на прежнее место, потому что цель осталась старой.
     * Снаружи это выглядело как «прокрутка перестала работать».
     */
    if (out_of_bounds()) {
        edge = (scroll < 0) ? 0 : scroll_max;
        d = edge - scroll;
        fling = 0;

        if (d > -3 && d < 3) {
            scroll = edge;
            scroll_want = scroll;
            return 1;
        }

        /* Шаг — доля оставшегося пути: у самого края движение
         * замедляется само, а не обрывается на полпути */
        d = d * SPRING * dt / (100 * FRAME_MS);
        scroll += d ? d : (edge > scroll ? 1 : -1);
        scroll_want = scroll;
        return 1;
    }

    /*
     * Двигаем с накоплением остатка.
     *
     * Скорость в пикселях в секунду, время в миллисекундах, а координата
     * целая: при 200 px/с за кадр набегает три с лишним пикселя, и
     * дробная часть каждый раз пропадала. На глаз это ступеньки — список
     * то стоит, то прыгает. Остаток теперь переносится в следующий кадр.
     */
    {
        int move = fling * dt + frac;

        scroll -= move / 1000;
        frac = move % 1000;
        scroll_want = scroll;
    }

    /* Затухание по миллисекундам: сколько прошло, столько раз и гасим */
    for (int i = 0; i < dt; i++)
        fling = fling * DECAY / 1000;

    /*
     * Долетели до края на скорости — пусть выскочит за него и вернётся
     * пружиной. Резко обрывать движение нельзя: именно по отскоку глаз
     * понимает, что список кончился, а не застрял.
     */
    if (scroll < -RUBBER_MAX) {
        scroll = -RUBBER_MAX;
        fling = 0;
    } else if (scroll > scroll_max + RUBBER_MAX) {
        scroll = scroll_max + RUBBER_MAX;
        fling = 0;
    }

    if (fling < FLICK_MIN && fling > -FLICK_MIN)
        fling = 0;

    return 1;
}

/* --- Разбор касаний ------------------------------------------------- */

static void vsample(u32 y, u64 ms)
{
    if (vn < VSAMPLES) {
        vy[vn] = y;
        vt[vn] = ms;
        vn++;
        return;
    }
    for (u32 i = 1; i < VSAMPLES; i++) {
        vy[i - 1] = vy[i];
        vt[i - 1] = vt[i];
    }
    vy[VSAMPLES - 1] = y;
    vt[VSAMPLES - 1] = ms;
}

/*
 * Скорость броска — по последним точкам, а не по всему жесту.
 *
 * Важно, как палец двигался в конце: медленно провёл и резко дёрнул
 * напоследок — список должен полететь. По двум соседним событиям
 * получается дёрганно (между ними бывает три миллисекунды и один
 * пиксель), поэтому берём окно из нескольких точек.
 */
static int gesture_velocity(void)
{
    u64 dt;
    int v;

    if (vn < 2)
        return 0;

    dt = vt[vn - 1] - vt[0];
    if (!dt)
        return 0;

    v = ((int)vy[vn - 1] - (int)vy[0]) * 1000 / (int)dt;
    if (v > FLICK_MAX)
        v = FLICK_MAX;
    if (v < -FLICK_MAX)
        v = -FLICK_MAX;

    return v;
}

/*
 * Запустить приложение.
 *
 * Второй раз запускать не даём: окно у программы одно, слоёв под окна
 * два, и десяток копий одного приложения не нужен никому. Если оно уже
 * работает — значит его просто спрятали полоской «домой», и вернуть его
 * той же полоской и надо.
 */
static void launch_app(void)
{
    s64 id;

    /*
     * Уже запущенное — вернуть на экран, а не молчать. Нажимая на
     * приложение, человек хочет его увидеть; узнавать от системы, что
     * оно «и так работает», ему незачем.
     */
    if (app_task) {
        if (window_raise(app_task) == 0) {
            write("EL0      : ОБОЛОЧКА: ВЕРНУЛА ПРИЛОЖЕНИЕ НА ЭКРАН\n");
            return;
        }
        app_task = 0;           /* окна нет — значит программы больше нет */
    }

    id = spawn(IMG_HITTIS);
    if (id > 0) {
        app_task = (u64)id;
        write("EL0      : ОБОЛОЧКА: ЗАПУСТИЛА ПРИЛОЖЕНИЕ\n");
    } else {
        write("EL0      : ОБОЛОЧКА: ПРИЛОЖЕНИЕ НЕ ЗАПУСТИЛОСЬ\n");
    }
}

static void on_down(const struct touch *t)
{
    touches++;

    /* Экран выключения держится до касания и им же снимается */
    if (off_screen) {
        off_screen = 0;
        return;
    }

    /*
     * Касание во время полёта только останавливает список и ничего не
     * выбирает. Так ведёт себя всякий приличный список: палец ловит
     * убегающий текст, а не открывает то, на что случайно попал.
     */
    stopped_fling = scroll_busy();
    fling = 0;

    {
        int b = btn_at(t->x, t->y);

        if (b >= 0) {
            if (armed == b && b == BTN_REBOOT) {
                write("EL0      : ОБОЛОЧКА: ПЕРЕЗАГРУЗКА ПО КНОПКЕ\n");
                reboot();
            }
            if (armed == b && b == BTN_OFF) {
                write("EL0      : ОБОЛОЧКА: ВЫКЛЮЧЕНИЕ ПО КНОПКЕ\n");
                /*
                 * Возвращается только при неудаче, и код говорит, какой
                 * именно: -3 значит «мешает кабель». Показать причину
                 * важнее, чем показать сам факт отказа: с кабелем
                 * человек может что-то сделать, с общим «не вышло» —
                 * ничего.
                 */
                power_screen("Выключаюсь", 0);

                off_rc = (int)power_off();
                if (!off_rc)
                    off_rc = -1;

                /*
                 * Сюда попадаем только если телефон остался жив.
                 * Показываем причину и держим её на экране, пока не
                 * коснутся: она важнее, чем скорее вернуть стол.
                 */
                if (off_rc == -3) {
                    power_screen("Не выключилось",
                                 "Отключи кабель и нажми снова");
                } else {
                    /*
                     * Код отказа — числом. Без него все неудачи
                     * выглядят одинаково, а их несколько разных: не
                     * сошлась проверка часов, не принял запись PMIC,
                     * записали и не погасло. Одна цифра на экране
                     * заменяет три догадки.
                     */
                    char why[48];
                    u32 n = 0;

                    const char *p = "Код отказа ";

                    while (*p)
                        why[n++] = *p++;
                    why[n++] = '-';
                    n += unum(why + n, (u64)(-off_rc));
                    why[n] = 0;
                    power_screen("Не выключилось", why);
                }
                off_screen = 1;
                armed = -1;
                return;
            }
            armed = b;
            off_rc = 0;
            armed_at = uptime_ms();
            return;
        }
    }

    if (armed >= 0)             /* нажали мимо — снимаем взвод */
        armed = -1;

    touching = 1;
    dragging = 0;
    down_x = t->x;
    down_y = t->y;
    down_scroll = scroll;
    scroll_want = scroll;
    down_ms = uptime_ms();
    vn = 0;
    vsample(t->y, down_ms);
    pressed = stopped_fling ? -1 : tile_at(t->x, t->y);
}

static void on_move(const struct touch *t)
{
    int dy;

    if (!touching)
        return;

    dy = (int)t->y - (int)down_y;

    /*
     * Пока палец не ушёл дальше порога, это ещё нажатие. Как только
     * ушёл — нажатие отменяется совсем: человек передумал и начал
     * прокрутку, и загоревшаяся под пальцем плитка была бы враньём.
     */
    if (!dragging && (dy > SLOP || dy < -SLOP)) {
        dragging = 1;
        pressed = -1;

        /*
         * Отсчёт начинаем ЗАНОВО, от этой точки.
         *
         * Иначе к списку сразу приезжает весь путь, пройденный до
         * порога, — четырнадцать пикселей одним прыжком. Особенно заметно,
         * когда докручиваешь: палец опустился, чуть сдвинулся, и список
         * дёрнулся, вместо того чтобы плавно пойти следом. Порог нужен,
         * чтобы отличить нажатие от ведения, а не чтобы копить смещение.
         */
        down_y = t->y;
        down_scroll = scroll;
        dy = 0;
        vn = 0;
        vsample(t->y, uptime_ms());
    }

    if (!dragging)
        return;

    scroll_to(down_scroll - dy);
    vsample(t->y, uptime_ms());
}

static void on_up(const struct touch *t)
{
    int was = pressed;

    if (!touching) {
        pressed = -1;
        return;
    }
    touching = 0;
    pressed = -1;

    if (dragging) {
        vsample(t->y, uptime_ms());
        fling = gesture_velocity();
        if (fling < FLICK_MIN && fling > -FLICK_MIN)
            fling = 0;          /* просто отпустили, а не бросили */
        dragging = 0;
        return;
    }

    /* Касание, которым поймали летящий список, ничего не выбирает */
    if (!stopped_fling && was >= 0 && tile_at(t->x, t->y) == was) {
        chosen = was;
        if (was == TILE_APP)
            launch_app();
    }
}

/* --- Точка входа ---------------------------------------------------- */

void _start(void) __attribute__((section(".text.start")));

void _start(void)
{
    u64 shown_sec;

    pressed = -1;
    chosen = -1;
    armed = -1;         /* у программы в EL0 не бывает начальных значений */

    screen_size(&sw, &sh);
    if (!sw || !sh) {
        write("EL0      : ОБОЛОЧКА: ЭКРАНА НЕТ\n");
        exit(1);
    }

    win = window(sw, sh);
    if (!win) {
        write("EL0      : ОБОЛОЧКА: ОКНА НЕ ДАЛИ\n");
        exit(2);
    }

    tile_w = (sw - 2 * MARGIN - (COLS - 1) * GAP) / COLS;
    list_top = HEADER_H;
    list_bottom = sh - BAR_H;
    content_h = ((TILE_COUNT + COLS - 1) / COLS) * (TILE_H + GAP) + GAP;
    scroll_max = (int)content_h - (int)(list_bottom - list_top);
    if (scroll_max < 0)
        scroll_max = 0;

    /* Показывается первая половина, рисуем во вторую */
    half = 1;
    back = win + (u64)sw * sh;

    /*
     * Система просыпается заблокированной, как и положено телефону.
     *
     * Рабочий стол за экраном блокировки уже построен и ждёт: разбор
     * касаний, прокрутка и плитки к блокировке отношения не имеют, а
     * держать два набора состояний ради одного экрана незачем.
     */
    locked = 1;
    lock_full = 2;      /* обе половины буфера — с чистого фона */
    draw_lock();
    show();

    if (present(0, 0) != 0) {
        write("EL0      : ОБОЛОЧКА: ПОКАЗАТЬ ОКНО НЕ ВЫШЛО\n");
        exit(3);
    }

    write("EL0      : ОБОЛОЧКА В EL0 ЗАПУЩЕНА, ЖЕСТЫ И ПРОКРУТКА\n");
    shown_sec = uptime_ms() / 1000;

    for (;;) {
        struct touch t;
        s64 got;
        int moving = scroll_busy() || scroll != scroll_want;
        int redraw = 0;

        /*
         * Ждём пальца, а когда список движется — почти не ждём.
         *
         * Здесь была потеря половины кадров. Стояло ожидание в целый
         * кадр: пока список летит, событий нет, цикл честно высыпал
         * шестнадцать миллисекунд и только потом принимался рисовать —
         * а рисование с показом стоят ещё шестнадцать. Тридцать две
         * миллисекунды на кадр, тридцать кадров в секунду вместо
         * шестидесяти, и именно это выглядело дёрганым.
         *
         * Ждать незачем: показ и так привязан к развёртке панели и сам
         * держит нас ровно на шестидесяти кадрах. Миллисекунда нужна
         * только чтобы забрать событие, если оно уже пришло.
         */
        /*
         * Ждём касания, но никогда не бесконечно.
         *
         * Прежде на рабочем столе стояло ожидание без срока: пальца нет
         * — программа спит, пока он не появится. Это было верно ровно до
         * того, как появилась кнопка питания: её никто не опросил бы
         * никогда, потому что спящая программа не спрашивает ничего.
         *
         * Сроки разные по надобности. Список летит — миллисекунда, лишь
         * забрать уже пришедшее. Экран погашен или заперт — пятая доля
         * секунды, там торопиться некуда. Обычная работа — десятая, это
         * десять опросов кнопки в секунду и незаметная задержка нажатия.
         */
        got = moving ? input_wait(&t, 1)
                     : input_wait(&t, (locked || screen_off) ? 200 : 100);

        /*
         * Кнопка питания: гасит экран и возвращает его.
         *
         * Спрашиваем в цикле, а не по прерыванию: кнопка живёт в
         * контроллере питания, на своей шине, и заводить ради неё
         * прерывание через весь путь до программы значило бы много
         * работы ради нажатия, которое случается раз в минуту.
         *
         * Погасив, запираем сразу. Иначе возврат показал бы рабочий стол
         * с того самого места — а телефон, который просыпается уже
         * открытым, замок и не имеет вовсе.
         */
        if (power_key() == 1) {
            if (screen_off) {
                screen_off = 0;
                lock_full = 2;
                screen_blank(0);
                draw_lock();
                show();
            } else {
                screen_off = 1;
                locked = 1;
                lock_full = 2;
                strip_wallpaper(1);
                lock_drag = 0;
                /*
                 * Рисуем замок ДО гашения, а не после возврата: пока
                 * экран погашен, рисовать некуда торопиться, зато при
                 * возврате кадр уже готов и не мелькает старым.
                 */
                draw_lock();
                show();
                screen_blank(1);
            }
            continue;
        }

        /*
         * Пока погашено — не рисуем ничего и не разбираем касаний.
         *
         * Экран тёмный, и всякая работа в него уходит впустую. Касания
         * при этом тоже игнорируем: телефон в кармане нажимает их
         * постоянно, и без этого он просыпался бы сам.
         */
        if (screen_off)
            continue;

        /*
         * Пока заблокировано — свой короткий разбор, и дальше не идём.
         *
         * Отдельная ветка, а не набор проверок внутри общего разбора:
         * здесь другой жест, другой кадр и другое всё. Смешивать их
         * значило бы усыпать разбор касаний проверками «а мы не
         * заблокированы?» в десятке мест, и однажды одну забыть.
         */
        if (locked) {
            /*
             * Ждём не дольше секунды, даже когда ничего не происходит:
             * минута может смениться и без касаний, а часы, отстающие
             * до первого прикосновения, — это часы сломанные.
             */
            if (got != 1) {
                s64 now = lock_clock();

                /*
                 * Дорисовываем то, что не успели показать при движении:
                 * иначе палец, остановившийся между кадрами, оставил бы
                 * содержимое не там, где он его держит.
                 */
                if (lock_drag != lock_drawn) {
                    u64 t0 = uptime_ms(), t1;

                    draw_lock();
                    t1 = uptime_ms();
                    show();
                    lock_drawn = lock_drag;

                    /*
                     * Отчёт о времени кадра.
                     *
                     * Раз в шестьдесят кадров, а не на каждый: печать
                     * сама стоит времени, и мерить ею же — верный способ
                     * измерить собственную печать. Складываем целые
                     * миллисекунды: по одному кадру разрешения не хватит,
                     * по шестидесяти — вполне.
                     */
                    frm_draw += t1 - t0;
                    frm_show += uptime_ms() - t1;
                    if (++frm_n >= 60) {
                        char m[96];
                        u32 k = 0;

                        k += ulabel_n(m + k, "ЗАМОК: 60 КАДРОВ, РИСОВАНИЕ ",
                                      frm_draw);
                        k += ulabel_n(m + k, " МС, ПОКАЗ ", frm_show);
                        k += ulabel_n(m + k, " МС, ВСЕГО ",
                                      uptime_ms() - frm_at);
                        m[k++] = ' '; m[k++] = 'M'; m[k++] = 'C';
                        m[k++] = '\n'; m[k] = 0;
                        write(m);
                        frm_n = 0;
                        frm_draw = 0;
                        frm_show = 0;
                        frm_at = uptime_ms();
                    }
                } else if (now >= 0 && (CLOCK_HOUR(now) != lock_hh ||
                                        CLOCK_MIN(now) != lock_mm)) {
                    draw_lock();
                    show();
                }
                continue;
            }

            /*
             * Забираем ВСЕ накопившиеся движения и оставляем последнее.
             *
             * Тачскрин присылает сто двадцать событий в секунду, а
             * показать мы успеваем шестьдесят кадров: flip внутри себя
             * ждёт промежутка между кадрами. Разбирая события по одному
             * на кадр, мы отставали бы всё сильнее — очередь растёт, и
             * текст едет за пальцем с накапливающимся опозданием. Это и
             * выглядит как «лагает».
             *
             * Промежуточные положения пальца никому не нужны: на экране
             * всё равно окажется только последнее.
             */
            if (t.action == TOUCH_MOVE) {
                struct touch nt;

                while (input_wait(&nt, 1) == 1) {
                    t = nt;
                    if (t.action != TOUCH_MOVE)
                        break;      /* палец подняли — это уже не движение */
                }
            }

            if (t.action == TOUCH_DOWN) {
                /*
                 * Разблокировка начинается ТОЛЬКО у нижнего края.
                 *
                 * Раньше годился любой свайп вверх откуда угодно, и это
                 * мешало: всякое движение по экрану норовило снять
                 * блокировку. В телефоне тянут за полоску внизу, и жест
                 * от этого становится намеренным, а не случайным.
                 *
                 * Полоска живёт в системной полосе, ниже нашего окна,
                 * поэтому касание по ней приходит с координатой больше
                 * высоты окна — отсюда и порог «ниже, чем h минус
                 * UNLOCK_ZONE», а не «внутри полоски».
                 */
                down_y = t.y;
                lock_drag = 0;
                lock_from_edge = ((int)t.y >= (int)sh - UNLOCK_ZONE);
            } else if (t.action == TOUCH_MOVE) {
                int up = (int)down_y - (int)t.y;

                if (!lock_from_edge)
                    continue;   /* жест начался не у полоски — не наш */
                if (up < 0)
                    up = 0;
                lock_drag = up;
                /*
                 * Своего ограничения по времени здесь НЕТ и быть не
                 * должно: flip и так ждёт промежутка между кадрами, то
                 * есть частоту задаёт экран. Порог, который я поставил
                 * сюда сначала, лишь добавлял задержку поверх этого
                 * ожидания и отодвигал кадр за следующую развёртку.
                 */
                if (lock_drag != lock_drawn) {
                    draw_lock();
                    show();
                    lock_drawn = lock_drag;
                }
            } else {                    /* отпустили */
                if (lock_drag >= LOCK_SWIPE) {
                    locked = 0;
                    lock_drag = 0;
                    lock_drawn = 0;
                    strip_wallpaper(0);     /* стол тёмный, обои убрать */
                    write("EL0      : ОБОЛОЧКА: РАЗБЛОКИРОВАНО\n");
                    draw_all();
                    show();
                } else if (lock_drag) {
                    /* Не дотянул — содержимое возвращается на место */
                    lock_drag = 0;
                    lock_drawn = 0;
                    draw_lock();
                    show();
                }
            }
            continue;
        }

        /*
         * Палец, о котором давно ничего не слышно, считаем отпущенным.
         *
         * Событие «отпустили» может не дойти — потеряться в очереди,
         * уйти системе, не случиться вовсе. Программа, которая на него
         * рассчитывает безоговорочно, залипает навсегда: считает, что
         * палец на экране, перерисовывается без остановки и не выбирает
         * ничего. Так и было, и лечить это только в ядре мало —
         * приличная программа должна переживать потерю события.
         */
        if (touching && uptime_ms() - last_seen_ms > 500) {
            struct touch fake;

            fake.x = (u16)down_x;
            fake.y = (u16)down_y;
            fake.id = 0;
            fake.action = TOUCH_UP;
            on_up(&fake);
            redraw = 1;
        }

        /*
         * Панель управления перехватывает касания ЦЕЛИКОМ, пока открыта.
         *
         * Иначе палец, ведущий ползунок яркости, заодно прокручивал бы
         * список под стеклом — а список под ним есть всегда.
         */
        /*
         * Панель управления пока выключена по просьбе: экран блокировки
         * ещё не доведён до макета, и держать поверх него недоделанную
         * панель незачем. Код не удалён — снять оба условия обратно
         * дешевле, чем писать заново.
         */
        if (PANEL_ON && panel_open && got == 1) {
            int bx, by, bw, bh;

            bright_box(&bx, &by, &bw, &bh);
            if (t.action != TOUCH_UP &&
                (int)t.x >= bx - 40 && (int)t.x <= bx + bw + 40 &&
                (int)t.y >= by && (int)t.y <= by + bh) {
                /* Ползунок вертикальный: низ — темнее, верх — ярче */
                int pc = (by + bh - (int)t.y) * 100 / bh;

                if (pc < 0)
                    pc = 0;
                if (pc > 100)
                    pc = 100;
                screen_bright((u32)pc);
                draw_all();
                draw_panel();
                show();
            } else if (t.action == TOUCH_UP && (int)t.y > (int)sh - 320) {
                panel_open = 0;
                draw_all();
                show();
            }
            last_seen_ms = uptime_ms();
            continue;
        }

        /*
         * Открытие панели: тянем вниз от верхнего края.
         *
         * Начало жеста ограничено верхней полосой, иначе всякая
         * прокрутка списка вниз открывала бы панель.
         */
        if (PANEL_ON && !panel_open && got == 1) {
            if (t.action == TOUCH_DOWN && (int)t.y < PANEL_GRAB) {
                panel_drag = (int)t.y;
            } else if (t.action == TOUCH_MOVE && panel_drag &&
                       (int)t.y - panel_drag > PANEL_PULL) {
                panel_open = 1;
                panel_drag = 0;
                on_up(&t);          /* список не должен считать это прокруткой */
                draw_all();
                draw_panel();
                show();
                last_seen_ms = uptime_ms();
                continue;
            } else if (t.action == TOUCH_UP) {
                panel_drag = 0;
            }
        }

        if (got == 1) {
            last_seen_ms = uptime_ms();
            if (t.action == TOUCH_DOWN)
                on_down(&t);
            else if (t.action == TOUCH_MOVE)
                on_move(&t);
            else
                on_up(&t);
            redraw = 1;
        }

        if (fling_step())
            redraw = 1;
        if (follow_finger())
            redraw = 1;

        /* Взведённая кнопка гаснет сама: иначе случайное касание через
         * час перезагрузило бы телефон. */
        if (armed >= 0 && uptime_ms() - armed_at > BTN_ARM_MS) {
            armed = -1;
            redraw = 1;
        }

        if (uptime_ms() / 1000 != shown_sec) {
            shown_sec = uptime_ms() / 1000;
            redraw = 1;
        }

        if (off_screen)
            redraw = 0;         /* причина отказа висит, пока не коснутся */

        if (redraw) {
            u64 t0 = uptime_ms();
            u64 t1;

            draw_all();
            t1 = uptime_ms();
            show();
            draw_sum += t1 - t0;

            /*
             * Раз в секунду говорим, во сколько обходится кадр. Спорить
             * о плавности словами бессмысленно: либо кадр укладывается в
             * шестнадцать миллисекунд, либо нет, и это видно числом.
             */
            frame_sum += uptime_ms() - t0;
            frame_count++;
            if (frame_count >= 30 && uptime_ms() - frame_told > 1000) {
                frame_told = uptime_ms();
                ulabel(line, "EL0      : ОБОЛОЧКА: КАДР ",
                       frame_sum / frame_count);
                {
                    const char *mid = ", ИЗ НИХ РИСОВАНИЕ ";
                    u32 n = ustrlen(line);

                    for (u32 k = 0; mid[k]; k++)
                        line[n++] = mid[k];
                    unum(line + n, draw_sum / frame_count);
                }
                line[ustrlen(line)] = 10;
                line[ustrlen(line) + 1] = 0;
                write(line);
                frame_sum = 0;
                draw_sum = 0;
                frame_count = 0;
            }
        }
    }
}
