/*
 * Первая программа на Си для EL0.
 *
 * Нужна ради проверки пути сборки: компилятор, свой скрипт компоновки,
 * образ без заголовков, вшитый в ядро, и запуск по фиксированному
 * адресу. Пока это не работает, писать оболочку бессмысленно — а на
 * ассемблере её писать не стоит и подавно.
 *
 * Заодно проверяет два места, где программе легко упасть: изменяемые
 * данные (они лежат по другому адресу, ядро отображает их отдельно) и
 * стек (он у неё свой).
 */
#include "ulib.h"

/* Без начального значения: инициализированных глобальных у программ
 * для EL0 не бывает, и компоновщик за этим следит. */
static u64 counter;
static char line[64];

void _start(void) __attribute__((section(".text.start")));

void _start(void)
{
    u64 me = getpid();

    write("EL0      : ПРИВЕТ ИЗ ПРОГРАММЫ НА СИ\n");

    for (counter = 0; counter < 3; counter++) {
        ulabel(line, "EL0      : КРУГ ", counter + 1);
        line[ustrlen(line)] = '\n';
        line[ustrlen(line)] = 0;
        write(line);
        sleep_ms(400);
    }

    ulabel(line, "EL0      : СИ-ПРОГРАММА, ЗАДАЧА ", me);
    line[ustrlen(line)] = '\n';
    line[ustrlen(line)] = 0;
    write(line);

    exit(0);
}
