#ifndef PMM_H
#define PMM_H
#include "types.h"

/*
 * Физический аллокатор страниц.
 *
 * Первый настоящий менеджер памяти в ядре: до него вся память, которой мы
 * распоряжались, была статическими массивами в .bss. Теперь у нас есть
 * гигабайты, и кто-то должен вести им учёт.
 *
 * Устройство самое простое из работающих — битовая карта: один бит на
 * страницу в 4 КБ, 0 свободна, 1 занята. Для 4 ГБ это миллион бит,
 * то есть 128 КБ карты — меньше сотой доли процента памяти.
 *
 * Почему не список свободных страниц, который выдаёт страницу за O(1):
 * ему негде хранить себя, кроме тех же страниц, а нам ещё нужны блоки
 * из НЕСКОЛЬКИХ подряд идущих страниц (под ту же карту, под кучу, потом
 * под стеки задач). По битовой карте такой поиск очевиден, по списку —
 * нет. Скорость выделения здесь пока никого не волнует.
 */

#define PAGE_SIZE   4096UL
#define PAGE_SHIFT  12

/* Разметить память. Всё, что лежит ниже конца образа ядра, и сам DTB
 * помечаются занятыми — их нам никто не отдавал. */
int pmm_init(u64 ram_base, u64 ram_size, u64 dtb_phys);

/* Пометить занятым произвольный диапазон (например, фреймбуфер) */
void pmm_reserve(u64 start, u64 size);

/* Выделить одну страницу / count подряд идущих. Память обнуляется.
 * NULL означает, что памяти не осталось. */
void *pmm_alloc(void);
void *pmm_alloc_pages(u32 count);

void  pmm_free(void *page);
void  pmm_free_pages(void *page, u32 count);

/* Статистика в страницах */
void  pmm_stats(u64 *total, u64 *used);

#endif
