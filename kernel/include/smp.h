#ifndef SMP_H
#define SMP_H
#include "types.h"

/*
 * Многоядерность.
 *
 * У Helio G85 восемь ядер, но после загрузки работает ровно одно: остальные
 * держит выключенными прошивка, и разбудить их можно только через PSCI.
 * До сих пор нам этого хватало, а с появлением планировщика семь спящих
 * ядер — это семь восьмых впустую потраченного процессора.
 *
 * У каждого ядра появляется своя структура struct cpu. Указатель на неё
 * лежит в TPIDR_EL1 — регистре, специально отведённом ядру ОС под такие
 * нужды. Это заметно лучше, чем каждый раз искать себя по MPIDR: на
 * телефоне номера ядер идут не подряд (два кластера), и поиск по таблице
 * пришлось бы делать в каждом обработчике прерывания.
 */

#define MAX_CPUS    8

struct task;

struct cpu {
    u64 id;                     /* логический номер: 0, 1, 2, ...        */
    u64 mpidr;                  /* аппаратный идентификатор              */
    u64 gicr;                   /* база своего редистрибьютора GIC       */
    u64 ticks;                  /* прерываний таймера на этом ядре       */
    /*
     * Сколько из них застало ядро на холостом ходу.
     *
     * Считаем именно так — по тикам, а не по времени, — потому что тик
     * приходит сто раз в секунду независимо ни от чего, и отношение
     * одного счётчика к другому сразу даёт долю занятости. Ничего
     * измерять отдельно не нужно, а нагрев идёт ровно отсюда: занятое
     * ядро греется, спящее на wfi — почти нет.
     */
    u64 idle_ticks;
    struct task *current;       /* что исполняется прямо сейчас          */
    struct task *idle;          /* чем занять ядро, когда работы нет     */
    struct task *dying;         /* только что завершилась, стек ещё занят */
    volatile u32 resched;       /* пора вытеснить текущую задачу         */
    volatile u32 online;
};

void        percpu_init(u32 id, u64 mpidr);
struct cpu *this_cpu(void);
struct cpu *cpu_of(u32 id);
u32         cpu_id(void);
u32         cpu_online_count(void);

/* Разбудить остальные ядра. Возвращает, сколько всего теперь работает. */
u32  smp_start_secondaries(void);
void smp_dump(void);

#endif
