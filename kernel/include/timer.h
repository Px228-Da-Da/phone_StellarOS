#ifndef TIMER_H
#define TIMER_H
#include "types.h"

/*
 * ARM Generic Timer как источник тиков ядра.
 *
 * Берём ВИРТУАЛЬНЫЙ таймер (CNTV_*, PPI 27), а не физический (CNTP_*, PPI 30).
 * Причина практическая: физический таймер из EL1 доступен только с разрешения
 * EL2 (CNTHCTL_EL2.EL1PCEN). В QEMU мы это разрешение выдаём сами в boot.S,
 * но на телефоне EL2 занят чужой прошивкой, и рассчитывать на её настройки
 * нельзя. Виртуальный таймер доступен из EL1 всегда — ровно поэтому и Linux
 * на телефонах тикает по нему.
 */

#define TIMER_IRQ_VIRT  27      /* PPI: virtual timer   */
#define TIMER_IRQ_PHYS  30      /* PPI: NS physical timer, пока не используем */

/* Запустить периодические прерывания с частотой hz. Требует поднятого GIC. */
int  timer_init(u32 hz);

/* То же на разбуженном ядре: частота уже известна, включаем свой таймер */
int  timer_init_cpu(void);

/* Сколько тиков насчитал обработчик прерывания с момента старта */
u64  timer_ticks(void);

/* Время с момента timer_init, в миллисекундах (по счётчику, не по тикам) */
u64  timer_uptime_ms(void);

#endif
