#ifndef WDT_H
#define WDT_H

/*
 * Сторожевой таймер: перезагружает телефон, если ядро замолчало.
 */

/* Что оставил загрузчик. Только чтение. */
void wdt_dump(void);

/* Повторить снимок регистров, снятый при загрузке. */
void wdt_report(void);

/* Взвести. После этого молчание дольше срока = перезагрузка. */
void wdt_start(void);

/* Погладить. Зовётся из тика; сама решает, с того ли ядра. */
void wdt_kick(void);

#endif
