#ifndef BATTERY_H
#define BATTERY_H
#include "types.h"

/*
 * Батарея: напряжение, заряд в процентах и признак зарядки.
 *
 * Мерит всё это сам PMIC — у MT6358 внутри есть аналого-цифровой
 * преобразователь, и батарея висит на его нулевом канале. Отдельной
 * микросхемы для этого не нужно.
 *
 * Все числа взяты из вендорного ядра merlin и из дерева устройств, а не
 * подобраны: адреса регистров из include/linux/mfd/mt6358/registers.h,
 * делитель и число усреднений из mt6358.dtsi, кривая разряда из
 * bat_setting/mt6768_battery_table.dtsi — это профиль ровно той батареи,
 * что стоит в этом телефоне.
 */

struct battery_state {
    u32 mv;             /* напряжение, милливольты */
    u32 percent;        /* заряд, 0..100           */
    int charging;       /* подключено ли питание   */
    int valid;          /* удалось ли измерить     */
    u32 raw;            /* сырой код АЦП: нужен, чтобы проверять формулу */
    int current_ma;     /* ток: плюс заряжается, минус разряжается       */
    u32 ocv_mv;         /* напряжение без нагрузки, по нему и процент    */
};

/* Измерить. Занимает около полутора миллисекунд: столько усредняет АЦП. */
void battery_read(struct battery_state *st);

/* Отвечает ли счётчик заряда: без него ток нулевой, а процент — по
 * напряжению на выводах, то есть с прежней ошибкой под нагрузкой. */
int battery_current_valid(void);

#endif
