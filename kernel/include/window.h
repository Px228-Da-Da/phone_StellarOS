#ifndef WINDOW_H
#define WINDOW_H
#include "types.h"

/*
 * Окно программы: кусок экрана, которым распоряжается EL0.
 *
 * До сих пор всё, что видно на экране, рисовало ядро. Программа в
 * пользовательском режиме не могла нарисовать ничего: ни фреймбуфера, ни
 * регистров контроллера дисплея ей не видно — и правильно, отдавать их
 * наружу нельзя. Отдаём другое: страницы буфера, отображённые в её
 * пространстве, и два системных вызова к ним.
 *
 * Дальше буфер читает сам контроллер дисплея, отдельным слоем поверх
 * кадра. Процессор при этом не копирует ни байта: программа пишет
 * пиксели, железо их показывает. Там, где слоёв нет (эмулятор), буфер
 * копируется в кадр — медленнее, зато одинаково работает везде.
 *
 * Буферы берутся из небольшого набора, заведённого раз и навсегда.
 * Причина не в экономии: буфер обязан быть некэшируемым, потому что
 * читает его не процессор, а другой блок, и пометка эта односторонняя.
 * Вернув такие страницы в общий котёл, мы раздавали бы дальше
 * некэшируемую память под что попало.
 */

/*
 * Сколько окон может существовать одновременно.
 *
 * Каждое занимает свой буфер в два мегабайта — навсегда, потому что
 * некэшируемую память возвращать в общий котёл нельзя. Поэтому число
 * небольшое и выбрано по числу программ, которые у нас показывают
 * что-то одновременно, а не «с запасом».
 */
#define WINDOW_MAX      4

/*
 * Потолок размера окна.
 *
 * Шестнадцать мегабайт — это экран телефона (1080x2340) с запасом.
 * Буфер под окно берётся по надобности, а не сразу весь: программе с
 * окошком в сто пикселей незачем двенадцать мегабайт.
 *
 * Уменьшаться буфер не умеет. Он некэшируемый, а такая пометка
 * односторонняя: вернуть эти страницы в общий котёл нельзя, иначе
 * некэшируемая память разойдётся дальше под что попало. Поэтому слот
 * помнит, сколько у него уже есть, и растёт только вверх.
 */
#define WINDOW_BYTES    (16UL * 1024 * 1024)

/*
 * Завести окно для ТЕКУЩЕЙ задачи и отобразить его буфер в её
 * пространстве. Возвращает адрес буфера в EL0 или 0.
 */
u64  window_open(u32 w, u32 h);

/* Показать окно в этом месте экрана. 0 — получилось. */
int  window_present(u32 x, u32 y);

/*
 * Написать строку в окне текущей задачи.
 *
 * Шрифт у ядра один, и отдавать его программам копиями ни к чему.
 * Рисуем мы при этом в её собственный буфер — то есть делаем ровно то,
 * что программа могла бы сделать сама, будь у неё шрифт.
 */
int  window_text(u32 x, u32 y, u32 scale, u32 fg, const char *s);

/*
 * Закрыть своё окно, не завершаясь.
 *
 * Программа, которой окно больше не нужно, освобождает и слот, и слой —
 * до сих пор всё это возвращалось только вместе с самой программой.
 * Буфер при этом остаётся за слотом: он некэшируемый, отдавать его в
 * общий котёл нельзя.
 */
int  window_close(void);

/*
 * Задача кончилась: убрать её окно с экрана и отобрать буфер.
 *
 * Зовётся сборщиком ДО того, как он разберёт адресное пространство:
 * отображение окна надо снять раньше, иначе разборщик посчитает буфер
 * обычной страницей программы и вернёт его в общий котёл.
 */
void window_task_gone(u64 task, u64 ttbr0);

#endif
