#ifndef SPI_H
#define SPI_H
#include "types.h"

/*
 * Контроллер SPI у MediaTek.
 *
 * На нём сидит тачскрин Novatek: узел spi0@1100a000, выбор кристалла 0,
 * частота 8 МГц. Загрузчик этой шиной не пользуется, поэтому её, скорее
 * всего, придётся поднимать с нуля — в отличие от I2C и PWRAP, которые
 * он оставил настроенными.
 *
 * Карта регистров восстановлена по драйверу Linux drivers/spi/spi-mt65xx.c
 * и проверяется тем же способом, что и раньше: сначала смотрим, что там
 * лежит на живом устройстве, и только потом пишем.
 */

/* Осмотреть контроллер тактирования: без него SPI мёртв */
void clk_probe(void);

/* Включить тактирование SPI0: без него блок читается нулями */
void spi_clk_enable(void);

/* Проверить, отвечает ли блок: записать и прочитать обратно */
void spi_alive_test(void);

/* Отдать выводы контроллеру SPI: без этого сигналы не доходят */
void spi_pins_setup(void);

/* Обмен по шине: приём идёт одновременно с передачей */
int  spi_transfer(const u8 *tx, u8 *rx, u32 len);

/* Максимум за одну посылку: столько байт держит очередь контроллера */
#define SPI_FIFO_MAX 32

/* Осмотреть блок, ничего не меняя */
void spi_probe(void);

#endif
