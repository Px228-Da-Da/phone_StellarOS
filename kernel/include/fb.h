#ifndef FB_H
#define FB_H
#include "types.h"

/*
 * Цвета в формате 0xAARRGGBB.
 *
 * Альфа обязана быть 0xFF, а не нулём. Панель merlin работает в ARGB8888,
 * и нулевая альфа означает «полностью прозрачно»: нарисованное не видно,
 * сквозь него просвечивает чёрный фон. Именно так выглядела первая рабочая
 * прошивка — экран чернел (наша заливка доходила до буфера), но текст на
 * нём не появлялся, потому что был прозрачным.
 */
#define COLOR_BLACK   0xFF000000
#define COLOR_WHITE   0xFFFFFFFF
#define COLOR_RED     0xFFFF0000
#define COLOR_GREEN   0xFF00FF00
#define COLOR_BLUE    0xFF0000FF
#define COLOR_YELLOW  0xFFFFFF00
#define COLOR_CYAN    0xFF00FFFF

int  fb_init(void);                     /* 0 = ок, экран есть */
int  fb_available(void);
void fb_clear(u32 color);
void fb_fill_rect(u32 x, u32 y, u32 w, u32 h, u32 color);
void fb_putc(char c);                   /* текстовая консоль поверх fb */
void fb_set_colors(u32 fg, u32 bg);

/*
 * Текст в произвольном месте кадра — для интерфейса, а не для консоли.
 * scale: во сколько раз растянуть глиф 8x8.
 * bg с нулевой альфой — прозрачный фон: закрашиваются только буквы.
 */
void fb_text(u32 x, u32 y, u32 scale, u32 fg, u32 bg, const char *s);

/*
 * То же, но в ЧУЖОЙ буфер, а не в кадр.
 *
 * Нужно окнам программ: шрифт живёт здесь, а рисовать надо туда, куда
 * покажут. Программе в EL0 своего шрифта взять негде — не потому, что
 * нельзя, а потому, что это лишние килобайты в каждой программе; отдать
 * ей ядерный проще и честнее, чем отдавать доступ к кадру.
 */
void fb_text_to(u32 *buf, u32 pitch_px, u32 bw, u32 bh,
                u32 x, u32 y, u32 scale, u32 fg, u32 bg, const char *s);

/*
 * Строка на экран в обход всего.
 *
 * Последний канал связи с человеком, когда ядро встало: контроллер
 * дисплея читает кадр сам, без нашего участия, поэтому написанное прямо
 * в память кадра видно даже если ни одно ядро больше ничего не делает.
 *
 * Пишем в ОБА буфера: какой из них показывается прямо сейчас, знать
 * неоткуда, а подменять буфер в таком положении уже некому.
 *
 * Никаких замков — их-то как раз и может не хватать. Испортить чужую
 * отрисовку здесь не жалко: если дошло до этого сообщения, картинка
 * больше не обновится.
 */
void fb_panic_text(u32 line, const char *s);
u32  fb_text_width(u32 scale, const char *s);
void fb_info(u64 *base, u32 *w, u32 *h, u32 *stride);

/*
 * Двойная буферизация. Пока она выключена, рисование идёт прямо в показываемый
 * буфер — для статичного текста этого достаточно. Для анимации включаем её:
 * тогда кадр рисуется в невидимый буфер, а fb_flip() показывает его целиком.
 *
 * Дорисовывать поверх предыдущего кадра после fb_flip() нельзя: в буфере,
 * куда мы вернулись, лежит кадр двухдавности. Каждый кадр рисуется заново.
 */
int  fb_double_buffer(int on);          /* включить/выключить, 0 = успех */
int  fb_double_buffered(void);
void fb_flip(void);                     /* показать нарисованное */
void fb_debug(void);                    /* адреса, геометрия, источник */

/* Сколько раз в секунду каждый блок цепочки вывода сообщает о кадре:
 * без этого числа непонятно, с чем вообще синхронизировать подмену */
void fb_vsync_probe(void);

/* Дождаться окна между кадрами.
 *
 * Настройки вывода — адрес буфера, положение и размер слоёв — меняются
 * только здесь: попадём в середину вывода, увидим шов. Возвращает 1,
 * если окно поймано, 0 — если не дождались за два кадра. */
int  fb_wait_frame_gap(void);

/* Не читает ли оверлей кадр прямо сейчас. Проверка перед самой записью:
 * окно короткое, и попасть в него мало — надо ещё в нём остаться. */
int  fb_frame_idle(void);

#endif
