#ifndef MDP_H
#define MDP_H

#include "types.h"

/*
 * Двумерный движок MediaTek: разведка.
 *
 * Зачем он нам. У телефона есть видеокарта Mali, но у неё нет никакой
 * двумерной части: ни залить прямоугольник, ни скопировать кусок памяти
 * она не умеет отдельным действием — на ней всё делается шейдерами, а
 * значит нужен компилятор шейдеров и разобранные по кусочкам регистры,
 * которых ARM не публикует. Это работа больше всей нашей системы.
 *
 * Зато рядом с оверлеем, которым мы уже управляем, лежит цепочка блоков,
 * делающих ровно то, чего нам не хватает:
 *
 *     mdp_rdma0   0x14004000   читает картинку из памяти
 *     mdp_rsz0    0x14006000   масштабирует
 *     mdp_wdma0   0x14008000   пишет обратно в память
 *     disp_wdma0  0x1400e000   пишет в память то, что показывает экран
 *     disp_rsz0   0x14015000   масштабирует в самой цепочке показа
 *
 * Уменьшить вчетверо и растянуть обратно — это и есть мягкое размытие,
 * и стоит оно нуля тактов процессора. Именно из-за дороговизны этой
 * части я и говорил, что размытия во весь экран нам не потянуть.
 *
 * Прежде чем что-то программировать, надо узнать, живы ли эти блоки:
 * тактируются ли они, что оставил в них загрузчик. Поэтому сначала —
 * только чтение. Тот же порядок, что с оверлеем, тачскрином и
 * контроллером питания: сперва посмотреть, потом трогать.
 */

/* Прочитать и напечатать состояние блоков. Ничего не меняет. */
void mdp_probe(void);

#endif
