#ifndef RAMFB_H
#define RAMFB_H
#include "types.h"

/*
 * ramfb — простой фреймбуфер QEMU.
 *
 * Зачем он нужен именно нам. У QEMU -M virt нет ни одного экрана, и до сих
 * пор вся отладка шла в UART. Но на телефоне вывод пойдёт на экран, и код
 * рисования — шрифт, консоль, прокрутка — иначе остаётся непроверенным
 * до первой прошивки.
 *
 * ramfb подходит лучше остальных вариантов, потому что устроен ровно как
 * экран телефона: линейный буфер пикселей в ОБЫЧНОЙ памяти, который
 * «контроллер дисплея» читает сам. Разница только в том, что там буфер
 * выделил загрузчик, а здесь мы даём свой и сообщаем его адрес.
 * Никакого PCI, никакого virtio — тот же fb.c рисует и там, и там.
 *
 * Договариваемся с QEMU через fw_cfg: находим файл "etc/ramfb" в его
 * каталоге и записываем туда параметры буфера.
 */

/* Сообщить QEMU, где наш буфер и какого он размера.
 * 0 — экран поднят, дальше можно просто писать пиксели. */
int ramfb_setup(u64 addr, u32 width, u32 height, u32 stride_bytes);

#endif
