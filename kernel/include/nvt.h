#ifndef NVT_H
#define NVT_H
#include "types.h"

/*
 * Тачскрин Novatek NT36xxx на шине SPI0.
 *
 * Протокол и все числа взяты из открытых исходников ядра Xiaomi для merlin:
 *   drivers/input/touchscreen/mediatek/NT36xxx_HOSTDL_SPI/
 *   arch/arm64/boot/dts/mediatek/merlin.dts, узел novatek@0 под &spi0
 * Это принципиально: раскладку регистров тачскрина не восстановить опытом,
 * а гадание тут стоит перепрошивки телефона на каждую попытку.
 *
 * Из дерева устройств merlin:
 *   сброс   — вывод 92, прерывание — вывод 1
 *   частота — 8 МГц, режим 0, старший бит первым
 */

/* Аппаратный сброс линией 92 и опознание микросхемы.
 * Печатает шесть байт идентификатора и имя микросхемы, если узнали. */
void nvt_probe(void);

/* Задать страницу адресного пространства контроллера */
int  nvt_set_page(u32 addr);

/* Записать один байт по адресу (страница выставляется сама) */
int  nvt_write_addr(u32 addr, u8 data);

/* Чтение: buf[0] — адрес внутри страницы, ответ ложится в buf[1..len-1] */
int  nvt_read(u8 *buf, u32 len);

/* Запись: buf[0] — адрес внутри страницы, дальше данные */
int  nvt_write(const u8 *buf, u32 len);

#endif
