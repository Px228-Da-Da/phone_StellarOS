#ifndef KMALLOC_H
#define KMALLOC_H
#include "types.h"

/*
 * Куча ядра — выделение блоков произвольного размера.
 *
 * Страничный аллокатор выдаёт куски по 4 КБ, а ядру постоянно нужны
 * структуры в десятки байт: узел списка, дескриптор задачи, буфер строки.
 * Отдавать под каждую целую страницу — потерять память в сотни раз.
 *
 * Куча берёт у pmm страницы оптом и нарезает их на блоки с заголовками,
 * связанные в список по возрастанию адреса. Порядок по адресу выбран
 * ради склейки: соседние свободные блоки нужно уметь объединять обратно,
 * иначе после тысячи выделений куча превратится в решето, где полно
 * свободной памяти, но нет ни одного достаточно большого куска.
 */

void *kmalloc(size_t size);
void *kzalloc(size_t size);         /* то же, но с обнулением */
void  kfree(void *ptr);

/* Статистика в байтах: сколько всего взято у pmm и сколько сейчас занято */
void  heap_stats(u64 *total, u64 *used, u64 *blocks);

#endif
