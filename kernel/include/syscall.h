#ifndef SYSCALL_H
#define SYSCALL_H

/*
 * Системные вызовы: единственная дверь из EL0 в ядро.
 *
 * Программе в пользовательском режиме недоступно ничего, кроме её
 * собственных страниц: ни регистров устройств, ни памяти ядра, ни даже
 * команды остановиться. Всё, что ей нужно от системы, она просит
 * командой SVC — процессор переключается в EL1 на наш обработчик, тот
 * делает работу и возвращает управление обратно.
 *
 * Соглашение выбрано такое же, как в Linux на AArch64, и не из
 * подражания: номер в отдельном регистре x8 оставляет x0..x5 целиком под
 * аргументы, а результат кладётся в x0 — то есть вызов выглядит и
 * работает как обычный вызов функции.
 *
 *   x8       номер вызова
 *   x0..x5   аргументы
 *   x0       результат; отрицательное значение — отказ
 */
#define SYS_EXIT        0       /* x0 — код завершения                  */
#define SYS_WRITE       1       /* x0 — адрес строки, x1 — длина        */
#define SYS_YIELD       2       /* уступить процессор                   */
#define SYS_SLEEP_MS    3       /* x0 — на сколько миллисекунд уснуть   */
#define SYS_UPTIME_MS   4       /* сколько система работает             */
#define SYS_GETPID      5       /* свой номер задачи                    */
#define SYS_SPAWN       6       /* x0 — номер программы; вернёт её задачу */
#define SYS_WAIT        7       /* x0 — номер задачи; вернёт её код       */
#define SYS_WINDOW      8       /* x0,x1 — размер; вернёт адрес буфера    */
#define SYS_PRESENT     9       /* x0,x1 — где показать окно              */
#define SYS_INPUT       10      /* x0 — куда положить событие касания;    */
                                /* x1 — сколько ждать, мс (0 — вечно)     */
#define SYS_TEXT        11      /* x0,x1 — место; x2 — размер;            */
                                /* x3 — цвет: буквы снизу, фон сверху;    */
                                /* x4,x5 — строка и её длина              */
#define SYS_SCREEN      12      /* размеры экрана: ширина<<32 | высота    */
#define SYS_CLOSE       13      /* закрыть своё окно, не завершаясь       */
#define SYS_FLIP        14      /* показать половину буфера: 0 или 1      */
#define SYS_REBOOT      15      /* перезагрузить телефон; не возвращается  */
#define SYS_RAISE       16      /* x0 — задача; показать её окно           */
#define SYS_POWEROFF    17      /* выключить телефон; вернётся лишь при    */
                                /* неудаче, с кодом PSCI                   */
#define SYS_APP         18      /* x0,x1 — куда и сколько; вернёт длину    */
                                /* принятого по проводу приложения, 0 —    */
                                /* значит работает вшитое в систему        */
#define SYS_TEXTW       19      /* x0 - razmer; x1,x2 - stroka i dlina;   */
                                /* vernyot shirinu, nichego ne risuya     */
#define SYS_CLOCK       20      /* vremya sutok iz RTC kontrollera pitaniya */
                                /* upakovano: chas<<40|min<<32|sek<<24|     */
                                /* den<<16|mesyats<<8|god; -1 esli net chasov */
#define SYS_PWRKEY      21      /* bylo li nazhatie knopki pitaniya:      */
                                /* 1 - da, i priznak snimaetsya           */
#define SYS_BLANK       22      /* x0: 1 pogasit ekran, 0 vernut          */
#define SYS_COUNT       23

/*
 * Событие касания в том виде, в каком его получает EL0.
 *
 * Раскладка обязана совпадать с struct input_event ядра: вызов копирует
 * её байт в байт. Программе она видна как четыре числа подряд —
 * x, y (по два байта) и номер пальца с действием (по одному).
 */
#define TOUCH_EVENT_BYTES   6

/*
 * Код, которым ядро помечает снятую им задачу.
 *
 * Отличается от любого кода, который программа может назначить себе
 * сама — иначе тот, кто её ждал, не отличил бы «завершилась с ошибкой»
 * от «была снята за нарушение».
 */
#define EXIT_KILLED     255

/*
 * Номера вшитых в образ программ — общий договор ядра и EL0.
 * Порядок обязан совпадать со списком images[] в uspace.c.
 */
#define IMG_HELLO       0
#define IMG_ROGUE       1
#define IMG_SPIN        2
#define IMG_TWIN        3
#define IMG_ONCE        4
#define IMG_BOSS        5
#define IMG_PAINT       6
#define IMG_TRACK       7
#define IMG_PANEL       8
#define IMG_HELLO_C     9
#define IMG_SHELL       10
#define IMG_HITTIS      11

/* Сколько байт за раз принимает SYS_WRITE. Ограничение обязательно:
 * длину задаёт программа, и без потолка она попросила бы ядро пройти
 * по гигабайту чужой памяти в одном непрерывном вызове. */
#define SYS_WRITE_MAX   512

#ifndef __ASSEMBLER__
#include "types.h"

/*
 * Кадр исключения — то, что vectors.S складывает на стек ядра при входе.
 * Порядок полей повторяет порядок stp в SAVE_REGS слово в слово: любое
 * расхождение здесь означает, что вызов прочитает не тот регистр, и
 * искать это придётся по неверному результату, а не по отказу.
 */
struct trapframe {
    u64 x[31];      /* x0..x30                                  */
    u64 elr;        /* куда возвращаться в программу            */
    u64 spsr;       /* состояние процессора на момент вызова    */
    u64 sp_el0;     /* стек программы: свой у каждой задачи     */
};

/* Вызывается из vectors.S на всякое синхронное исключение из EL0 */
void el0_sync(struct trapframe *f);

/* Прерывание, заставшее программу в EL0: считаем такие и передаём дальше */
void irq_from_el0(void);
u64  el0_preempt_count(void);

#endif /* __ASSEMBLER__ */
#endif
