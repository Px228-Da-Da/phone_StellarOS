#ifndef FDT_H
#define FDT_H
#include "types.h"

/*
 * Разбор device tree (FDT, он же DTB).
 *
 * Загрузчик передаёт нам в x0 адрес двоичного дерева, в котором описано
 * всё железо устройства. До сих пор мы только проверяли его заголовок,
 * а адреса брали из имён узлов, снятых с работающего Android. Дальше так
 * нельзя: главное, что нужно взять из дерева, в именах узлов не написано.
 *
 * Главное — это карта памяти. На merlin в /reserved-memory двадцать один
 * блок: ATF, TEE, буферы модема, фреймбуфер. Они лежат внутри той же DRAM,
 * которой распоряжается pmm, и закрыты аппаратно контроллером EMI:
 * обращение к ним из EL1 даёт не мусор, а мгновенную перезагрузку.
 * Пока мы их не читаем, прошивать своё ядро нельзя.
 *
 * Формат простой. Заголовок, затем три блока:
 *   memreserve  массив пар (адрес, размер) — устаревший способ резервирования
 *   struct      поток тегов: начало узла, свойство, конец узла
 *   strings     все имена свойств одной кучей, свойство хранит смещение в неё
 * Всё в big-endian, включая размеры — процессор у нас little-endian,
 * поэтому каждое число проходит через be32/be64.
 */

/* Область физической памяти */
struct fdt_region {
    u64 base;
    u64 size;
};

/* Проверить магию и версию. 0 — дерево пригодно к разбору. */
int fdt_check(u64 dtb_phys);

/* Общий размер дерева в байтах (нужен, чтобы зарезервировать его самого) */
u64 fdt_total_size(u64 dtb_phys);

/*
 * Собрать области из узлов /memory — это вся физическая память устройства.
 * Возвращает, сколько записей заполнено (не больше max).
 */
u32 fdt_memory(u64 dtb_phys, struct fdt_region *out, u32 max);

/*
 * Собрать области, которые трогать нельзя: и блок memreserve из заголовка,
 * и все узлы /reserved-memory с их reg.
 */
u32 fdt_reserved(u64 dtb_phys, struct fdt_region *out, u32 max);

/* Найти узел по имени (без адресной части) и прочитать его reg.
 * Пример: fdt_node_reg(dtb, "interrupt-controller", 1, &r) даст второй
 * диапазон gic — базу редистрибьюторов. */
int fdt_node_reg(u64 dtb_phys, const char *node_name, u32 index,
                 struct fdt_region *out);

/*
 * Найти узел по свойству compatible и прочитать index-й диапазон его reg.
 *
 * Именно по compatible, а не по имени: у одного и того же контроллера
 * имена узлов у всех разные — в QEMU это intc@8000000, у MediaTek
 * gic500@0c000000. А строка "arm,gic-v3" одна и та же везде, потому что
 * по ней драйверы и опознают железо.
 */
int fdt_compatible_reg(u64 dtb_phys, const char *compat, u32 index,
                       struct fdt_region *out);

/*
 * Прочитать index-е прерывание узла с данным compatible и перевести его
 * в номер INTID, каким его знает GIC.
 *
 * В дереве прерывание записано тройкой ячеек <тип номер флаги>. Тип 0 —
 * это SPI (устройства), и настоящий INTID у него номер + 32; тип 1 — PPI
 * (приватные для ядра, среди них таймеры), INTID = номер + 16. Драйвер
 * не должен знать про это смещение — fdt_interrupt возвращает уже готовый
 * INTID, который можно отдать в gic_enable_irq.
 *
 * Пример: у узла arm,armv8-timer четыре прерывания, третье (index 2) —
 * виртуальный таймер; на нашем железе это выходит INTID 27.
 */
#define FDT_IRQ_SPI  0
#define FDT_IRQ_PPI  1

int fdt_interrupt(u64 dtb_phys, const char *compat, u32 index, u32 *intid_out);

/* Запомнить дерево, переданное загрузчиком, чтобы не таскать адрес всюду */
void fdt_set_root(u64 dtb_phys);
u64  fdt_root(void);

/* Строковое свойство корня, например "model" или "compatible" */
const char *fdt_root_string(u64 dtb_phys, const char *prop);

#endif
