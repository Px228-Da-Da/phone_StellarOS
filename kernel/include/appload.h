#ifndef APPLOAD_H
#define APPLOAD_H

#include "types.h"

/*
 * Приложения приезжают по проводу, а не вшиваются в систему.
 *
 * До сих пор приложение на Hittis жило внутри образа ядра: правишь .ht,
 * пересобираешь всю систему, гонишь телефон в fastboot, прошиваешь. На
 * одно исправление опечатки — полторы минуты и три действия руками. Так
 * никто ничего не пишет.
 *
 * Канал берём тот, что уже есть: та же консоль по USB, по которой идёт
 * вывод ядра. Приёмную точку мы объявляли хосту с самого начала, но не
 * читали; теперь читаем. Никаких записей в память телефона при этом не
 * делается вовсе — приложение живёт в оперативной памяти и уходит с
 * перезагрузкой. Это осознанный размен: постоянное хранение потребовало
 * бы записи в раздел, а правило про «карту только читаем» дороже, чем
 * удобство не терять приложение при перезагрузке.
 *
 * Посылка выглядит так:
 *
 *     !SLT <байт> <сумма>\n
 *     <шестнадцатеричные цифры, переводы строк где угодно>
 *     !END\n
 *
 * Разметка нарочно из латиницы и цифр: на проводе не должно быть ничего,
 * что зависит от кодировки терминала. Шестнадцатеричные цифры вместо
 * сырых байт — по той же причине: приложение весит килобайты, удвоение
 * ничего не стоит, зато посылка проходит через любой последовательный
 * порт и читается глазами, когда что-то идёт не так.
 */

/* Завести задачу, которая слушает провод и принимает приложения */
void appload_start(void);

/*
 * Принятое приложение: адрес и длина. Возвращает 0, если ничего не
 * присылали — тогда работает то, что вшито в систему.
 */
const u8 *appload_image(u32 *len);

#endif
