#ifndef CHARGER_H
#define CHARGER_H
#include "types.h"

/*
 * Контроллер заряда SMB1351 на шине I2C7, адрес 0x55.
 *
 * Он решает, сколько тока брать из кабеля и сколько отдавать батарее.
 * Наше ядро к нему до сих пор не обращалось: заряд шёл на том, что
 * оставил загрузчик. Измерения показали, что этого впритык хватает на
 * собственное потребление и не хватает, чтобы батарея росла.
 *
 * Карта регистров из вендорного драйвера merlin
 * (drivers/power/supply/mediatek/charger/smb1351-charger.c).
 *
 * Пока только чтение. Заряд — это про безопасность батареи, и менять
 * ток или напряжение вслепую нельзя: сначала надо увидеть, что
 * контроллер уже настроен, что он видит на кабеле и в каком состоянии
 * находится сам.
 */

struct charger_state {
    int valid;          /* ответил ли контроллер   */
    u8  version;
    u8  current_ctrl;   /* ток заряда и предел по входу */
    u8  input_limit;    /* режим входа: 100/500/AC      */
    u8  chg_cmd;        /* команды заряда               */
    u8  status4;        /* стадия заряда                */
    u8  status5;        /* что распознано на кабеле     */
    u32 input_ma;       /* предел по входу, мА          */
    u32 charge_ma;      /* ток заряда, мА               */
};

/* Опросить контроллер. Ничего не меняет. */
int charger_probe(struct charger_state *st);

/* Напечатать состояние по-человечески */
void charger_dump(void);

/*
 * Вернуть выбор предела входного тока самому контроллеру.
 *
 * Загрузчик задаёт предел жёсткой командой — 500 мА, потолок обычного
 * порта компьютера. Пока телефон подключён к компьютеру, это и правильно.
 * Но команда действует всегда, и от настоящего зарядника телефон брал бы
 * те же 500 мА: контроллер просто не смотрит, что на кабеле.
 *
 * Мы не поднимаем ток и не назначаем свой предел. Мы возвращаем решение
 * тому, кто умеет его принимать: контроллер сам распознаёт тип источника
 * и берёт ровно столько, сколько источник разрешает. Больше, чем
 * позволяет кабель, он не возьмёт.
 */
int charger_use_apsd(void);

/* Стадия заряда и распознанный источник — строкой, для интерфейса */
const char *charger_stage_text(void);
const char *charger_port_text(void);
u32 charger_input_ma(void);

#endif
