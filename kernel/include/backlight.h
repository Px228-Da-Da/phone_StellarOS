#ifndef BACKLIGHT_H
#define BACKLIGHT_H
#include "types.h"

/*
 * Подсветка экрана — то, что делает погашенный экран действительно
 * погашенным, а не просто чёрным.
 */

/* Найти микросхему подсветки и понять её. Печатает, что нашла. */
void backlight_probe(void);

/* Опознана ли раскладка: 0 — подсветкой управлять не умеем */
int backlight_known(void);

/* Включить (1) или выключить (0). Яркость сохраняется. */
void backlight_set(int on);

/* Яркость 0..100 процентов. 0 — получилось, -1 — управления нет. */
int backlight_level(u32 percent);

/* Текущая яркость в процентах, -1 если управления нет. */
int backlight_percent(void);

#endif
