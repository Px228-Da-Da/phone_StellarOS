#ifndef SPLASH_H
#define SPLASH_H

#include "types.h"

/*
 * Заставка загрузки.
 *
 * Пока система поднимается, человеку нужно видеть, что она поднимается.
 * Раньше на экране шёл зелёный лог ядра — он честный, но обращён к тому,
 * кто этот лог писал; всем остальным он говорит только «что-то
 * происходит, и, кажется, не то».
 *
 * Заставка не притворяется: полоса показывает настоящие шаги загрузки, а
 * не заранее нарисованное движение. Шаги перечислены ниже, и каждый
 * отмечается там, где он действительно закончился.
 */

#define SPLASH_SCREEN   1       /* экран найден                  */
#define SPLASH_CONSOLE  2       /* консоль по USB поднята        */
#define SPLASH_MEMORY   3       /* память посчитана и роздана    */
#define SPLASH_IRQ      4       /* прерывания и таймер работают  */
#define SPLASH_CPUS     5       /* остальные ядра подняты        */
#define SPLASH_TASKS    6       /* планировщик раздаёт время     */
#define SPLASH_PROGRAMS 7       /* программы EL0 запущены        */
#define SPLASH_SHELL    8       /* оболочка на экране            */

/* Первый кадр — сразу после того, как нашёлся экран */
void splash_show(void);

/* Шаг загрузки позади. Номер — из перечисления в splash.c */
void splash_stage(u32 done);

/* Задача плавности: проявление логотипа и движение полосы */
void splash_task(void *arg);

/* Оболочка на экране — заставка больше не нужна */
void splash_finish(void);

#endif
