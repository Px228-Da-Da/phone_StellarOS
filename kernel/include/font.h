#ifndef FONT_H
#define FONT_H

#include "types.h"

/*
 * Настоящий шрифт: Manrope, растрированный со сглаживанием.
 *
 * Ядро кривые не разбирает — их развернул в пиксели tools/fontgen ещё при
 * сборке. Здесь остаётся только найти знак и положить его на место: ни
 * дробных чисел, ни выделения памяти, ни разбора TrueType в ядре нет и
 * быть не должно.
 *
 * У каждого знака своя ширина — шрифт пропорциональный. Это меняет
 * привычку, оставшуюся от клеточного 8x8: ширину строки нельзя считать
 * умножением, её надо складывать (fb_text_width).
 *
 * Начертания заготовлены на несколько кеглей. Растягивать одно на все
 * размеры нельзя: сглаженные пиксели при растягивании превращаются в
 * мыло, ради которого сглаживание и не стоило затевать.
 */

struct font_face {
    u32 px;             /* кегль в пикселях                          */
    u32 line;           /* высота строки                             */
    u32 base;           /* от верха строки до базовой линии          */
    u32 count;          /* сколько знаков                            */
    const u32 *codes;   /* коды знаков, по возрастанию               */
    const u8  *glyphs;  /* по 8 байт на знак                         */
    const u8  *bits;    /* прозрачность, байт на пиксель             */
};

struct font_glyph {
    const u8 *bits;     /* w*h байт прозрачности; 0 — рисовать нечего */
    u32 w, h;
    u32 adv;            /* насколько сдвинуться вправо                */
    int left, top;      /* от точки вывода и от базовой линии         */
};

/* Шрифт лежит в образе куском, границы ставит src/font_data.S */
extern const u8 font_blob_start[];
extern const u8 font_blob_end[];

/* Разобрать вшитый в образ шрифт. 0 — годен. */
int font_init(const u8 *blob, u32 len);

/* Начертание, ближайшее к запрошенному кеглю; 0 — шрифта нет вовсе */
const struct font_face *font_pick(u32 px);

/* Знак в начертании; 0 — такого знака в шрифте нет */
int font_glyph(const struct font_face *f, u32 cp, struct font_glyph *out);

#endif
