#ifndef INPUT_H
#define INPUT_H
#include "types.h"

/*
 * Ввод как служба системы.
 *
 * До сих пор тачскрин опрашивался прямо посреди загрузки: пятнадцать
 * секунд ядро не делало ничего другого, а после этого ввода не было
 * вовсе. Для интерфейса так нельзя — он должен получать касания всё
 * время, пока работает.
 *
 * Устройство простое: отдельная задача опрашивает контроллер сто раз в
 * секунду и складывает события в кольцо, а интерфейс их оттуда забирает
 * когда ему удобно. Никто никого не ждёт.
 *
 * Сами касания контроллер отдаёт состоянием — «сейчас на стекле такие-то
 * пальцы», — а интерфейсу нужны переходы: нажали, ведут, отпустили.
 * Разницу считает опрос, сравнивая с прошлым разом.
 */

enum touch_action {
    TOUCH_DOWN = 0,     /* палец опустился  */
    TOUCH_MOVE,         /* ведёт по стеклу  */
    TOUCH_UP,           /* отпустил         */
};

struct input_event {
    u16 x, y;
    u8  id;             /* номер пальца, 1..10 */
    u8  action;
};

/* Запустить опрос: создаёт задачу в планировщике. Вызывать после
 * sched_init и после того, как тачскрин поднят. */
void input_start(void);

/* Забрать следующее событие. Возвращает 0, если очередь пуста. */
int  input_pop(struct input_event *e);

/*
 * Канал ожидания ввода.
 *
 * Число произвольное, важно лишь, чтобы ждущий и будящий назвали одно и
 * то же. Опрос будит этот канал каждый раз, когда положил событие в
 * очередь: ждать касание можно сном, а не опросом.
 */
#define INPUT_CHAN      0x1000BEEFUL

/*
 * Своя очередь для программы в EL0.
 *
 * Очередь одна, а желающих несколько: оболочка ядра и сколько-то
 * программ. Забирать из общей очереди наперегонки нельзя — событие
 * достаётся кому-то одному, и остальные его не видят вовсе. Наружу это
 * выглядит как «касания иногда не доходят», и разбираться в этом
 * тяжело: всё работает, просто не у всех.
 *
 * Поэтому у каждой программы своя очередь. Опрос кладёт событие во все
 * сразу — их единицы, и копия события стоит шесть байт.
 *
 * Подписка заводится первым же обращением: программа, которая ввод не
 * спрашивает, очереди не занимает. Событий до подписки она не увидит —
 * так и должно быть, они случились без неё.
 */
int  input_pop_task(u64 task, struct input_event *e);

/* Задача кончилась — освободить её очередь */
void input_unsubscribe(u64 task);

/* Сколько событий потеряно из-за переполнения очереди: если растёт,
 * значит потребитель не успевает. */
extern u32 input_dropped;

#endif
