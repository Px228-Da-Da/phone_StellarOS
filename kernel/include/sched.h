#ifndef SCHED_H
#define SCHED_H
#include "types.h"

/*
 * Планировщик: вытесняющий, с общей очередью готовых задач.
 *
 * Задача — это стек и сохранённый на нём контекст. Переключение сводится
 * к тому, чтобы сложить регистры x19..x30 на стек текущей задачи, поменять
 * SP на стек следующей и снять регистры оттуда. Остальные регистры (x0..x18)
 * сохранять не нужно: по соглашению AArch64 их и так вправе испортить любой
 * вызов функции, а переключение всегда происходит через вызов.
 *
 * Вытеснение — из обработчика прерывания таймера: когда задача израсходовала
 * свой квант, ядро помечает «пора переключиться», и переключение происходит
 * сразу после выхода из обработчика. Кооперативная уступка тоже есть — это
 * тот же schedule(), вызванный самой задачей.
 *
 * Очередь одна на все ядра, под спинлоком. Очередь на каждое ядро масштабируется
 * лучше, но требует балансировки между ядрами; на восьми ядрах и десятке задач
 * общая очередь и проще, и честнее — зато задачи реально разбегаются по всем
 * ядрам сами.
 */

/*
 * Квант: два тика таймера = 20 мс.
 *
 * Был 50 мс. Для счётных задач разницы нет, а для отклика на касание
 * есть: разбуженная задача с высоким приоритетом всё равно ждёт, пока
 * текущая доработает свой квант, и этот квант — нижняя граница задержки.
 */
#define TASK_SLICE_TICKS    2

/*
 * Приоритеты.
 *
 * Больше — важнее. Уровней нужно ровно два: то, что ждёт человека, и всё
 * остальное. Ввод и оболочка обязаны получать процессор сразу, как им
 * есть что делать, иначе нажатие срабатывает с задержкой в полсекунды —
 * ровно это и было, пока очередь была честно круговой.
 */
#define TASK_PRIO_NORMAL    0
#define TASK_PRIO_UI        1

enum task_state {
    TASK_READY = 0,     /* в очереди, ждёт процессора */
    TASK_RUNNING,       /* исполняется на каком-то ядре */
    TASK_SLEEPING,      /* ждёт срока, в очереди готовых её нет */
    TASK_DONE,          /* завершилась */
};

struct task;

typedef void (*task_fn)(void *arg);

/* Общая часть: очередь и список задач. Вызывается один раз на CPU0. */
void sched_init(void);

/* Своя idle-задача для текущего ядра. Вызывается на каждом ядре. */
void sched_init_cpu(void);

struct task *task_create(const char *name, task_fn fn, void *arg);

/* То же, но с приоритетом: для задач, которые ждут человека */
struct task *task_create_prio(const char *name, task_fn fn, void *arg,
                              u32 prio);

/*
 * Задача со своим адресным пространством — то есть пользовательская.
 *
 * Пространство задаётся при создании, а не после: задача попадает в
 * очередь готовых сразу, и другое ядро вправе забрать её раньше, чем мы
 * успеем что-либо дописать. Такая задача ушла бы в пользовательский
 * режим по таблицам ядра, где её страниц нет.
 */
struct task *task_create_space(const char *name, task_fn fn, void *arg,
                               u32 prio, u64 ttbr0);

/*
 * Уснуть на заданное время.
 *
 * Задача, которой нечего делать до срока, обязана спать, а не уступать
 * процессор в пустом цикле: уступка сразу возвращает её в очередь
 * готовых, и с высоким приоритетом она заберёт всё время себе.
 */
void task_sleep_ms(u64 ms);

/* Отдать процессор: выбрать следующую задачу и переключиться на неё */
void schedule(void);

/* Из обработчика таймера: посчитать квант и решить, пора ли вытеснять */
void sched_tick(void);

/* Завершить текущую задачу */
void task_exit(void);

/* Бесконечный цикл для ядра, которому нечего делать */
void sched_idle_loop(void);

/* Вызывается сразу после переключения контекста, в том числе из ассемблера */
void sched_after_switch(void);

void sched_dump(void);
u32  sched_task_count(void);

/*
 * Кто исполняется прямо сейчас — номер и имя.
 *
 * Понадобилось системным вызовам: программа в EL0 не знает о себе ничего
 * и спрашивает свой номер у ядра, а сообщения ядра о её ошибках без
 * имени задачи читаются как «кто-то что-то нарушил».
 */
u64         task_id(void);
const char *task_name(void);

#endif
