#ifndef PMIC_H
#define PMIC_H
#include "types.h"

/*
 * PMIC MT6358 через обёртку PWRAP.
 *
 * Процессор не общается с PMIC напрямую: тот сидит на отдельной
 * последовательной шине, а между ними стоит аппаратная обёртка PWRAP
 * (pwrap@1000d000). Мы кладём в её регистр команду, она сама гоняет
 * посылку и возвращает ответ.
 *
 * Зачем это нам: питание тачскрина идёт от регулятора VLDO28 внутри PMIC,
 * и загрузчик его не включает. Без PMIC до касаний не добраться.
 *
 * Смещения регистров PWRAP восстановлены по драйверу Linux
 * drivers/soc/mediatek/mtk-pmic-wrap.c и проверяются опытом: если канал
 * настроен верно, PMIC вернёт свой идентификатор.
 */

/* Указать смещения регистров PWRAP: у разных поколений MediaTek они
 * различаются, и нужный вариант находится опытом. */
void pmic_use_regs(u32 cmd, u32 rdata, u32 vldclr);

/* Найти смещения перебором: спрашиваем у PMIC идентификатор по каждому
 * возможному адресу внутри блока, пока не получим осмысленный ответ.
 * Возвращает смещение регистра команды или 0, если не нашлось. */
u32  pmic_find_regs(u16 *id_out);
void pmic_set_spins(u32 n);

/* Прочитать регистр PMIC. 0 — успех, значение в out. */
int pmic_read(u32 reg, u16 *out);

/* Записать регистр PMIC. 0 — успех. */
int pmic_write(u32 reg, u16 val);

/* Нажата ли кнопка питания прямо сейчас: 1 — да */
int pmic_powerkey(void);

/* Идентификатор микросхемы: первое, чем стоит проверять канал */
#define MT6358_SWCID        0x000A

/* Регуляторы, до которых нам есть дело */
#define MT6358_LDO_VLDO28_CON0      0x1C08
#define MT6358_LDO_VLDO28_OP_EN     0x1C0A

#endif
