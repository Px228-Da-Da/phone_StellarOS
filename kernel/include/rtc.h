#ifndef RTC_H
#define RTC_H

#include "types.h"

/*
 * Настоящее время суток — из контроллера питания.
 *
 * Не путать с timer_uptime_ms(): тот считает от включения и о времени
 * суток не знает ничего. Часы в контроллере питания идут от своей
 * батарейки, в том числе пока телефон выключен.
 */
struct rtc_time {
    u8 sec, min, hour;
    u8 day, dow, month;
    u8 year;                /* лет от 2000-го */
};

/* Прочитать. Ноль — вышло, минус — не вышло (например, на эмуляторе). */
int rtc_now(struct rtc_time *t);

#endif
