#ifndef GPIO_H
#define GPIO_H
#include "types.h"

/*
 * Выводы общего назначения (GPIO) у MediaTek.
 *
 * Нужны для тачскрина: у него две линии, сброс на выводе 92 и прерывание
 * на выводе 1. Без сброса контроллер не запустить, без чтения линии
 * прерывания не узнать, что палец коснулся экрана.
 *
 * Контроллер по адресу 0x10005000 снят с живого устройства
 * (узел gpio@10005000). Настройка подтяжек живёт отдельно, в восьми банках
 * io_cfg по 0x10002000 — их пока не трогаем: загрузчик уже всё настроил,
 * а лишняя запись может сломать то, что работает.
 */

/* Направление вывода */
#define GPIO_IN     0
#define GPIO_OUT    1

int  gpio_get_dir(u32 pin);         /* GPIO_IN или GPIO_OUT */
int  gpio_get_mode(u32 pin);        /* 0 — обычный вывод, иначе спецфункция */
int  gpio_read(u32 pin);            /* состояние линии */
int  gpio_read_out(u32 pin);        /* что мы сами туда выставили */

void gpio_set_dir(u32 pin, int dir);
void gpio_write(u32 pin, int value);

#endif
