#ifndef UIAREA_H
#define UIAREA_H

#include "types.h"

/*
 * Рабочая область — экран без системных полос.
 *
 * Сверху узкая полоса состояния: там вырез камеры, там же время и
 * заряд. Снизу полоска, которой на телефонах показывают «домой». Всё
 * остальное — рабочая область, и она целиком принадлежит приложению.
 *
 * Полосы принадлежат системе, и приложение до них не дотягивается вовсе:
 * окно ему выдаётся не больше рабочей области и ставится внутрь неё.
 * Это не запрет из вежливости, а свойство: программа в EL0 рисует только
 * в свой буфер, а куда этот буфер попадёт на экране, решает ядро.
 *
 * Отсюда простое следствие для приложений: спрашивая размер экрана, они
 * получают размер рабочей области. Другого экрана у них нет.
 */

/*
 * Полоса состояния сверху.
 *
 * Было 96, стало 128 — и не ради красоты. Вырез камеры у merlin уходит
 * вниз примерно до 110-й строки, то есть ВЫЛЕЗАЛ за полосу в окно
 * программы. Пока полоса была просто фоном, это никого не трогало; но
 * «пилюля» вокруг выреза, как в макете, рисуется системой и обязана
 * накрыть его целиком, иначе снизу торчит чёрный огрызок.
 *
 * Плата за это — тридцать две точки рабочей области. Их не жалко:
 * содержимое туда всё равно не ставят, там вырез.
 */
#define UI_STATUS_H     128     /* полоса состояния сверху */
#define UI_HOME_H       48      /* полоска «домой» снизу   */

/* Размеры рабочей области и её начало на экране */
void ui_area(u32 *x, u32 *y, u32 *w, u32 *h);

/* Обновить часы и заряд. Фон полос при этом не трогается: он кладётся
 * один раз, иначе полосы мигают на каждом обновлении. */
void ui_status_draw(void);

/* Нарисовать полосы заново целиком — после того, как кадр залили */
void ui_status_repaint(void);

/*
 * Насколько поднять содержимое полосы вслед за пальцем.
 *
 * Экран блокировки уезжает вверх за жестом, и значок заряда обязан
 * ехать вместе с ним: иначе он один остаётся висеть на месте, и жест
 * распадается на две несогласованные части.
 *
 * Полосу рисует ядро, а жест видит оболочка — поэтому сдвиг она и
 * сообщает. Сама полоса при этом остаётся системной: приложение не
 * может ни спрятать её, ни нарисовать в ней своё.
 */
void ui_strip_lift(u32 px);

/* Чем закрашивать полосы: 1 — обоями (замок), 0 — сплошным (стол) */
void ui_strip_wallpaper(int on);

/* Завести задачу, которая держит полосы в порядке */
void ui_status_start(void);

#endif
