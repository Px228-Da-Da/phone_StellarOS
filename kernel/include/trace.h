#ifndef TRACE_H
#define TRACE_H
#include "types.h"
#include "smp.h"

/*
 * Следы, переживающие перезагрузку.
 *
 * Задача одна: узнать, чем были заняты ядра в тот миг, когда система
 * встала. Обычный вывод для этого не годится в принципе — доставляет его
 * тот же тик, который остановился, и всё, что ядро успело сказать
 * напоследок, остаётся лежать в памяти.
 *
 * Значит и писать надо сразу в память, а не в очередь на отправку. Здесь
 * ровно это: у каждого ядра своя ячейка, в неё кладётся одно число —
 * чем оно сейчас занято. Сторожевой таймер перезагружает телефон, DRAM
 * при тёплой перезагрузке содержимое сохраняет, и на следующей загрузке
 * мы эти ячейки читаем и печатаем.
 *
 * Стоит это одной записи без замков и без чтения — дешевле некуда, иначе
 * ставить отметки в горячих местах было бы нельзя.
 *
 * Ячейка на ядро, а не общее кольцо, нарочно: кольцо потребовало бы
 * согласования между ядрами, а нам нужен снимок «кто где стоял», и он
 * получается сам собой.
 */

#define TR_NONE       0
#define TR_IDLE       1     /* спит на wfi                        */
#define TR_TICK       2     /* обработчик таймера                 */
#define TR_SYSCALL    3     /* вызов из программы, номер в младших */
#define TR_USER       4     /* вернулись в программу              */
#define TR_PMIC       5     /* обмен с контроллером питания       */
#define TR_USB        6     /* отдаём вывод в провод              */
#define TR_FLIP       7     /* ждём промежутка между кадрами      */
#define TR_WALL       8     /* копируем обои в окно               */
#define TR_TEXT       9     /* пишем текст в окно                 */
#define TR_STRIP     10     /* системные полосы                   */
#define TR_TOUCH     11     /* тачскрин                           */
#define TR_SCHED     12     /* переключение задач                 */

struct trace_slot {
    u64 what;               /* код места и, где нужно, подробность */
    u64 seq;                /* растёт при каждой отметке           */
    u64 ticks;              /* сколько тиков видело это ядро       */
};

extern struct trace_slot trace_slots[8];

/*
 * Отметиться. Одна запись, никаких замков: отметка не обязана быть
 * согласованной с другими ядрами, она обязана быть дешёвой.
 */
static inline void trace(u32 code, u32 detail)
{
    u32 c = cpu_id();

    if (c < 8) {
        trace_slots[c].what = ((u64)code << 32) | detail;
        trace_slots[c].seq++;
        /*
         * Счётчик тиков кладём сюда же. По нему видно главное: встали
         * все ядра разом или засыпали по одному. Если у всех число
         * одинаковое — прерывания пропали для всех сразу, и виновато
         * что-то общее. Если у кого-то оно сильно меньше — это ядро
         * замолчало раньше остальных, и начинать надо с него.
         */
        trace_slots[c].ticks = this_cpu()->ticks;
    }
}

/* Снять снимок прошлой жизни. Зовётся В САМОМ НАЧАЛЕ загрузки, до того
 * как живые ядра начнут перезаписывать отметки. */
void trace_snapshot(void);

/* Напечатать снятое. Зовётся ПОЗЖЕ, когда заработала консоль. */
void trace_report(void);

/* Начать новую жизнь: пометить область своей и обнулить. */
void trace_begin(void);

#endif
