#ifndef USB_H
#define USB_H
#include "types.h"

/*
 * Контроллер USB 2.0 (MUSB) у MediaTek.
 *
 * Зачем: у ядра нет ни одного канала связи с компьютером. UART выведен на
 * тест-пойнты внутри корпуса, а fastboot живёт в загрузчике, который мы
 * затираем. Пока единственный способ увидеть вывод — фотографировать экран.
 *
 * USB это меняет: телефон определится в системе как последовательный порт,
 * и весь kprintf пойдёт прямо в терминал.
 *
 * Наблюдение с устройства: при обычной загрузке загрузчик USB не поднимает
 * (телефон пропадает с шины, как только стартует наше ядро). Значит
 * перечисление устройства придётся делать полностью самим.
 *
 * Адреса сняты с устройства: usb0@11200000, второй блок 0x11CC0000,
 * физический уровень usb1p_sif@11210000, прерывание INTID 129.
 */

/* Осмотреть контроллер, ничего не меняя. Печатает, что нашлось. */
void usb_probe(void);

/* Осмотреть блоки физического уровня */
void usb_phy_probe(void);

/* Разбудить физический уровень: без этого линия мертва */
void usb_phy_on(void);

/* Включить подтяжку на линии: с этого момента хост нас видит */
void usb_connect(void);

/* Сколько запросов пришло на нулевую точку: видно, говорит ли с нами хост */

/* Один шаг обслуживания нулевой точки: вызывать почаще, иначе хост
 * решит, что устройство неисправно, и объявит перечисление неудачным */
void usb_poll(void);

/* Отправить байты хосту. До перечисления молча ничего не делает. */
void usb_send(const u8 *data, u32 len);

/* Вывод символа в консоль поверх USB: копится и уходит строкой */
void usb_putc(char c);
void usb_flush(void);

/* Перечислились ли: хост выбрал конфигурацию */
int  usb_ready(void);
extern u32 usb_setup_count;

/*
 * Забрать байт, присланный компьютером. Возвращает 1, если он был.
 *
 * Приёмную точку мы объявляли хосту с самого начала, но не читали —
 * и это работало ровно до первого байта в нашу сторону: очередь
 * заполнилась бы и встала навсегда. Теперь по этому каналу приезжают
 * приложения, и пересобирать систему ради нового больше не нужно.
 */
int  usb_recv(u8 *out);

/* Сколько байт потеряно: очередь мала или читатель не поспел */
u32  usb_rx_lost(void);

/* Сколько пакетов и байт пришло от компьютера. Число, а не догадка:
 * «дошло или нет» — первый вопрос, когда провод молчит. */
u32  usb_rx_packets(void);
u32  usb_rx_bytes(void);

/* Напечатать снятые при перечислении показания контроллера. Зовётся из
 * обычной задачи: снять их можно только под замком USB, а печатать под
 * ним нельзя — консоль идёт по тому же USB. */
void usb_report(void);

/* Следить за шиной и печатать, что происходило */
void usb_watch(u32 seconds);

#endif
