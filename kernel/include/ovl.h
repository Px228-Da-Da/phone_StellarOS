#ifndef OVL_H
#define OVL_H
#include "types.h"

/*
 * Слои контроллера дисплея — аппаратная композиция.
 *
 * До сих пор мы пользовались оверлеем как одним кадром: читали из его
 * регистра адрес буфера и писали туда свой. На самом деле слоёв четыре,
 * и складывает их железо, без единой записи в память.
 *
 * Что это даёт интерфейсу: фон отдельным слоем, панель отдельным, диалог
 * поверх с прозрачностью. Сдвинуть панель по экрану — записать одно число
 * в регистр положения; ни байта пикселей при этом не переписывается.
 * Ровно так в телефоне складываются окна на экране: рисует их содержимое
 * видеокарта, а складывает этот блок.
 *
 * Всё, что здесь есть, взято из вендорного ядра merlin
 * (drivers/misc/mediatek/video/mt6768/dispsys/ddp_ovl.c и ddp_reg_ovl.h),
 * кроме формата пикселя: его мы считываем с живого слоя 0, который
 * настроил загрузчик под уже работающий кадр. Это надёжнее любой таблицы —
 * там формат тот самый, что панель сейчас показывает.
 */

/* Показать, что настроил загрузчик. Только чтение. */
void ovl_dump(void);

/*
 * Положить буфер на слой.
 *
 * x, y      — где на экране
 * w, h      — размер
 * pitch     — байт в строке буфера
 * alpha     — 0..255, прозрачность всего слоя; 255 — непрозрачный
 *
 * Слой 0 занят основным кадром, поэтому свободны 1..3.
 * Возвращает 0 при успехе.
 */
int  ovl_layer_set(u32 layer, const volatile void *buf,
                   u32 x, u32 y, u32 w, u32 h, u32 pitch, u32 alpha);

/* Сдвинуть слой. Одна запись в регистр, память не трогаем. */
void ovl_layer_move(u32 layer, u32 x, u32 y);

/* Сменить прозрачность слоя. Тоже одна запись. */
void ovl_layer_alpha(u32 layer, u32 alpha);

/* Убрать слой с экрана */
void ovl_layer_off(u32 layer);

/* Слой сплошного цвета: буфера не нужно вовсе, цвет задаёт регистр.
 * Годится для затемнения фона под диалогом. */
int  ovl_layer_color(u32 layer, u32 argb, u32 x, u32 y, u32 w, u32 h);

#endif
