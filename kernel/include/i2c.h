#ifndef I2C_H
#define I2C_H
#include "types.h"

/*
 * Шина I2C контроллера MediaTek.
 *
 * Первое устройство ввода на этом телефоне сидит на I2C0: в дереве
 * устройства есть узел i2c0@11007000/cap_touch@5d — тачскрин по адресу 0x5D.
 *
 * Документации на MT6768 нет, карта регистров восстановлена по драйверу
 * Linux drivers/i2c/busses/i2c-mt65xx.c (раскладка версии 2). Поэтому
 * каждая операция ограничена по времени: ошибка в карте не должна
 * оборачиваться вечным ожиданием.
 *
 * Аппаратная очередь у контроллера всего восемь байт, длинные посылки
 * требуют DMA. Пока обходимся короткими: опрос шины и чтение регистров
 * тача в очередь помещаются.
 */

#define I2C_MAX_PIO     8               /* сколько байт влезает без DMA */

/* Проверить, отзывается ли устройство по адресу. 0 — отозвалось. */
int i2c_probe(u32 bus_base, u8 addr);

/* Записать буфер. 0 — успех. */
int i2c_write(u32 bus_base, u8 addr, const u8 *buf, u32 len);

/* Прочитать буфер. 0 — успех. */
int i2c_read(u32 bus_base, u8 addr, u8 *buf, u32 len);

/*
 * Записать, затем без отпускания шины прочитать — так читаются регистры
 * почти любой микросхемы: сперва отдаём номер регистра, потом читаем
 * значение. Отпустить шину между этими шагами нельзя, иначе устройство
 * забудет, что у него спрашивали.
 */
int i2c_write_read(u32 bus_base, u8 addr, const u8 *wbuf, u32 wlen,
                   u8 *rbuf, u32 rlen);

#endif
