#ifndef MMU_H
#define MMU_H
#include "types.h"

/*
 * Блок управления памятью.
 *
 * Пока MMU выключен, процессор трактует ВСЮ память как Device-nGnRnE:
 * никакого кэширования, никакого переупорядочивания, каждая запись идёт
 * до самой DRAM. Отсюда и медленная отрисовка. Включение MMU с кэшами
 * ускоряет работу с памятью в десятки раз.
 */

int  mmu_enable(void);

/* Включить MMU на текущем ядре по уже построенным таблицам.
 * Вызывается каждым вторичным ядром при запуске. */
int  mmu_enable_cpu(void);

/*
 * Пометить диапазон как некэшируемый.
 * Нужно для фреймбуфера: контроллер дисплея читает DRAM напрямую,
 * мимо кэшей процессора, и не знает о них ничего. Если оставить буфер
 * кэшируемым, пиксели осядут в кэше, а на экране останется старая картинка.
 */
void mmu_set_range_nc(u64 pa, u64 size);

/* Верхняя граница отображённой памяти. Всё, что выше, физически может
 * существовать, но трансляции для него нет — обращение туда даст ошибку. */
u64  mmu_ram_limit(void);

/*
 * Отображения для EL0.
 *
 * Ядру хватало блоков по два мегабайта, потому что отображение было одно
 * на всех и единичное. Пользовательской программе нужны страницы по 4 КБ:
 * её код, данные и стек — это единицы страниц, а раздавать права целыми
 * двухмегабайтными кусками означало бы отдать заодно всё, что случайно
 * попало в тот же кусок.
 *
 * Права даём тремя наборами, больше пока не требуется:
 */
#define MMU_USER_RX     1       /* читать и исполнять — код       */
#define MMU_USER_RW     2       /* читать и писать — данные, стек */
#define MMU_USER_RO     3       /* только читать                  */

int  mmu_map_user(u64 va, u64 pa, u64 size, u32 kind);

/*
 * Согласовать кэши после записи кода.
 *
 * Мы кладём программу в память обычной записью — она оседает в кэше
 * данных. Исполняться она будет через кэш инструкций, который о кэше
 * данных ничего не знает. Без этой процедуры процессор исполнит то, что
 * лежало в памяти ДО записи, — то есть мусор, и разбираться придётся уже
 * по адресу отказа.
 */
void mmu_sync_icache(u64 va, u64 size);

#endif
