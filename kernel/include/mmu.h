#ifndef MMU_H
#define MMU_H
#include "types.h"

/*
 * Блок управления памятью.
 *
 * Пока MMU выключен, процессор трактует ВСЮ память как Device-nGnRnE:
 * никакого кэширования, никакого переупорядочивания, каждая запись идёт
 * до самой DRAM. Отсюда и медленная отрисовка. Включение MMU с кэшами
 * ускоряет работу с памятью в десятки раз.
 */

int  mmu_enable(void);

/* Включить MMU на текущем ядре по уже построенным таблицам.
 * Вызывается каждым вторичным ядром при запуске. */
int  mmu_enable_cpu(void);

/*
 * Пометить диапазон как некэшируемый.
 * Нужно для фреймбуфера: контроллер дисплея читает DRAM напрямую,
 * мимо кэшей процессора, и не знает о них ничего. Если оставить буфер
 * кэшируемым, пиксели осядут в кэше, а на экране останется старая картинка.
 */
void mmu_set_range_nc(u64 pa, u64 size);

#endif
