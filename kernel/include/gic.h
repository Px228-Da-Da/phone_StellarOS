#ifndef GIC_H
#define GIC_H
#include "types.h"

/*
 * Контроллер прерываний GICv3.
 *
 * Почему сразу v3, а не привычный по учебникам v2: в merlin стоит GIC-500,
 * это v3 (узел gic500@0c000000 в device-tree живого телефона). У v3 нет
 * MMIO CPU-интерфейса — ack и EOI делаются системными регистрами ICC_*,
 * а SGI/PPI живут в редистрибьюторе, своём на каждое ядро. Код для v2
 * на этом телефоне просто не заработал бы, поэтому и QEMU запускаем
 * с gic-version=3: в эмуляторе отлаживаем именно ту дорогу.
 *
 * Нумерация прерываний общая для всех GIC:
 *    0..15   SGI  — межпроцессорные, понадобятся на этапе 4
 *   16..31   PPI  — приватные для ядра, среди них таймеры
 *   32..     SPI  — общие: устройства
 */

#define GIC_SGI_BASE    0
#define GIC_PPI_BASE    16
#define GIC_SPI_BASE    32
#define GIC_MAX_IRQS    256

/* Приоритет по умолчанию. Чем БОЛЬШЕ число, тем НИЖЕ приоритет.
 * Берём середину диапазона, чтобы потом было куда двигаться в обе стороны. */
#define GIC_PRIO_DEFAULT 0xA0

typedef void (*irq_handler_fn)(u32 intid);

/* CPU0: интерфейс своего ядра плюс общий дистрибьютор */
int  gic_init(void);

/* Любое ядро: только своё — регистры ICC_* и свой редистрибьютор */
int  gic_init_cpu(void);

/* Разрешить прерывание и назначить ему обработчик */
void gic_enable_irq(u32 intid, u32 prio, irq_handler_fn fn);

/* Вызывается из vectors.S через irq_handler(): разобрать все ждущие прерывания */
void gic_dispatch(void);

/* Диагностика: сколько прерываний обработано и сколько прилетело «ничьих» */
u64  gic_count(void);
u64  gic_spurious(void);

#endif
