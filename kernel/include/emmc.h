#ifndef EMMC_H
#define EMMC_H

/*
 * eMMC. Пока — только осмотр.
 *
 * Читаем регистры контроллера и печатаем их, не записывая ничего.
 * Смысл в том, чтобы увидеть, что оставил загрузчик: он читал с eMMC
 * наше ядро, значит контроллер настроен и работает. Опираться дальше
 * будем на увиденное, а не на память о вендорном драйвере.
 */
void emmc_probe(void);

/*
 * Прочитать один блок в 512 байт по номеру сектора. 0 — получилось.
 *
 * Читает на том контроллере, который оставил настроенным загрузчик:
 * карта уже опознана, адрес ей выдан, режим выбран. Наше дело —
 * выдать команду и забрать данные.
 */
int  emmc_read_block(u64 lba, void *dst);

#endif
