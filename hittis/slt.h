#ifndef SLT_H
#define SLT_H

/*
 * Формат приложений StellarOS: .slt
 *
 * Приложение — это не машинный код, а байткод для маленькой виртуальной
 * машины. Три причины, и все три существенные.
 *
 * Первая: ошибка в приложении не должна ронять ничего. Машина проверяет
 * каждый переход и каждое обращение к памяти сама, и худшее, что может
 * случиться, — приложение остановят с внятной жалобой.
 *
 * Вторая: файл получается маленьким и разбираемым. Заголовок читается
 * одним сектором, и по нему сразу видно, что это за приложение, сколько
 * ему нужно места на экране и цело ли оно.
 *
 * Третья: язык можно менять, не трогая ядро вообще. Ядро про Hittis не
 * знает ничего — оно запускает виртуальную машину, а та уже читает файл.
 *
 * Заголовок нарочно из полей постоянного размера: разбирать его должен
 * уметь и компилятор на компьютере, и машина на телефоне, где нет ни
 * библиотек, ни выделения памяти по требованию.
 */

#define SLT_MAGIC0  'S'
#define SLT_MAGIC1  'L'
#define SLT_MAGIC2  'T'
#define SLT_MAGIC3  '\0'

#define SLT_VERSION 1

#define SLT_NAME_MAX    32

/*
 * Заголовок. Все числа — младшим байтом вперёд, как и весь остальной
 * код на этой машине.
 */
struct slt_header {
    unsigned char  magic[4];        /* S L T \0                        */
    unsigned short version;         /* версия формата                  */
    unsigned short flags;           /* пока ноль, место на будущее      */

    char           name[SLT_NAME_MAX];  /* имя приложения для оболочки */

    unsigned short win_w;           /* какое окно просить у системы    */
    unsigned short win_h;           /* 0 — окно не нужно вовсе         */

    unsigned int   func_count;      /* сколько функций                 */
    unsigned int   global_count;    /* сколько глобальных переменных   */
    unsigned int   str_bytes;       /* длина области строк             */
    unsigned int   code_bytes;      /* длина байткода                  */

    unsigned int   checksum;        /* сумма всего, что после заголовка */
};

/*
 * За заголовком подряд: таблица функций, строки, байткод.
 *
 * Функция описывается входом в байткод и числом ячеек: сколько
 * принимает и сколько ей нужно всего. Разделять эти два числа
 * обязательно — по ним машина отводит кадр и понимает, куда класть
 * пришедшие значения.
 */
struct slt_func {
    unsigned int   entry;           /* смещение в байткоде             */
    unsigned short nargs;           /* сколько аргументов принимает    */
    unsigned short nlocals;         /* сколько ячеек нужно всего       */
};

/*
 * Команды машины.
 *
 * Машина стековая: у неё нет регистров, все действия берут операнды со
 * стека и кладут туда же результат. Так компилятор получается вдвое
 * проще — ему не нужно распределять регистры, — а разница в скорости
 * для приложений с интерфейсом никакой роли не играет: они всё равно
 * большую часть времени ждут палец.
 *
 * Операнд у команд, где он есть, — одно 32-битное число следом.
 */
enum slt_op {
    OP_HALT = 0,    /* конец программы                                */
    OP_PUSH,        /* положить число                                 */
    OP_PUSHS,       /* положить номер строки                          */
    OP_LOADL,       /* взять ячейку кадра                             */
    OP_STOREL,      /* записать в ячейку кадра                        */
    OP_LOADG,       /* взять глобальную                               */
    OP_STOREG,      /* записать глобальную                            */

    OP_ADD, OP_SUB, OP_MUL, OP_DIV, OP_MOD, OP_NEG,
    OP_LT, OP_GT, OP_LE, OP_GE, OP_EQ, OP_NE,
    OP_AND, OP_OR, OP_NOT,

    OP_JMP,         /* перейти                                        */
    OP_JZ,          /* перейти, если на вершине ноль                  */
    OP_CALL,        /* вызвать функцию: операнд — её номер            */
    OP_RET,         /* вернуться, значение на стеке                   */
    OP_NATIVE,      /* обратиться к системе: операнд — номер вызова   */
    OP_POP,         /* выбросить вершину                              */

    OP_COUNT
};

/*
 * Что приложение может попросить у системы.
 *
 * Это единственная дверь наружу: ни памяти, ни устройств, ни файлов
 * иначе как через этот список приложение не видит. Числа здесь —
 * договор между компилятором и машиной, менять их можно только вместе.
 */
enum slt_native {
    NAT_PRINT = 0,      /* напечатать строку в консоль                */
    NAT_PRINTN,         /* напечатать число                           */
    NAT_WINDOW,         /* завести окно: ширина, высота               */
    NAT_RECT,           /* прямоугольник: x, y, ш, в, цвет            */
    NAT_TEXT,           /* текст: x, y, размер, цвет, строка          */
    NAT_SHOW,           /* показать нарисованное                      */
    NAT_TOUCH,          /* дождаться касания: вернёт упакованные x,y  */
    NAT_SLEEP,          /* поспать миллисекунды                       */
    NAT_TIME,           /* сколько система работает, миллисекунд      */
    NAT_WIDTH,          /* ширина окна                                */
    NAT_HEIGHT,         /* высота окна                                */
    NAT_EXIT,           /* завершиться                                */

    NAT_COUNT
};

#endif
