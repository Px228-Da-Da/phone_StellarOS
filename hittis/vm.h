#ifndef HITTIS_VM_H
#define HITTIS_VM_H

/*
 * Виртуальная машина Hittis.
 *
 * Один и тот же исполнитель работает в двух местах: на компьютере, где
 * приложение проверяется без прошивки, и в телефоне, где он живёт
 * обычной программой в EL0. Разница между ними ровно одна — что делать,
 * когда приложение просит нарисовать или напечатать; поэтому всё
 * внешнее собрано в одну таблицу вызовов, а сама машина не знает ни про
 * системные вызовы, ни про printf.
 *
 * Машина недоверчива к приложению по построению. Она проверяет каждый
 * переход, каждое обращение к ячейке и глубину стека — и на любое
 * нарушение останавливается с внятной жалобой, а не портит память.
 * Приложение приходит с флешки, его мог испортить кто угодно, и «оно же
 * само себе не враг» здесь не работает.
 *
 * Машина не выделяет память вовсе: стек значений, кадры и глобальные
 * лежат в структуре, которую даёт вызывающий. На телефоне это важнее
 * всего — там просить память не у кого.
 */

typedef long long          vm_i64;
typedef unsigned int       vm_u32;
typedef unsigned short     vm_u16;
typedef unsigned char      vm_u8;

#define VM_STACK    256     /* глубина стека значений              */
#define VM_FRAMES   32      /* глубина вызовов                     */
#define VM_LOCALS   1024    /* общая площадь под кадры             */
#define VM_GLOBALS  256

/*
 * Куча под объекты.
 *
 * Тысяча ячеек — восемь килобайт. Больше взять негде: на телефоне
 * программе в EL0 отдано шестьдесят четыре килобайта изменяемых данных
 * на всё сразу, включая и стек машины, и место под само приложение.
 * Объект с пятью полями занимает шесть ячеек, то есть в кучу их влезает
 * под полторы сотни — для окна с кнопками этого с запасом.
 *
 * Возврата памяти нет намеренно. Сборщик мусора в машине, у которой
 * значения неотличимы от указателей, потребовал бы либо разметки типов,
 * либо честного обхода корней — и то и другое дороже, чем вся остальная
 * машина. Приложение живёт от запуска до закрытия окна, и куча уходит
 * вместе с ним.
 *
 * Тысячи ячеек оказалось мало, и это выяснилось не в рассуждении.
 * Калькулятор останавливался с «кончилась память под объекты», когда в
 * него набирали длинное число: показ числа складывает цифры в список, и
 * каждый показ занимал место навсегда.
 *
 * Восемь килобайт для приложения, которому отдан целый телефон, — это
 * скупость без причины. Шестнадцать тысяч ячеек это сто двадцать восемь
 * килобайт, и на фоне десятимегабайтного окна их незаметно.
 *
 * Но честно: это отодвигает границу, а не убирает её. Приложение,
 * заводящее списки в бесконечном цикле, однажды остановится всё равно.
 * Настоящее лечение — отличать указатель от числа, и тогда обход корней
 * становится возможным. До тех пор граница есть, и лучше, чтобы она была
 * далеко.
 */
#define VM_HEAP     16384

/* Что машина умеет попросить у мира. Ничего сверх этого ей не видно. */
struct vm_host {
    void    (*print)(const char *s);
    void    (*printn)(vm_i64 v);
    int     (*window)(int w, int h);
    void    (*rect)(int x, int y, int w, int h, vm_u32 color);
    void    (*text)(int x, int y, int scale, vm_u32 color, const char *s);
    void    (*textn)(int x, int y, int scale, vm_u32 color, vm_i64 v);
    /*
     * Один знак по коду, возвращает его ширину в точках.
     *
     * Нужен для ввода: строку язык сложить не умеет — у него нет ни
     * длины строки, ни обращения к её буквам, — поэтому набранное
     * хранится списком кодов и выводится по одному знаку. А шрифт у нас
     * не равноширинный, значит и ширину должен сообщать тот, кто рисует.
     */
    int     (*textc)(int x, int y, int scale, vm_u32 color, vm_i64 code);
    int     (*textw)(int scale, const char *s);
    void    (*show)(void);
    vm_i64  (*touch)(void);         /* см. договор о касании ниже        */
    void    (*sleep_ms)(vm_i64 ms);
    vm_i64  (*time_ms)(void);
    int     (*width)(void);
    int     (*height)(void);
};

/*
 * Как упаковано касание, которое возвращает touch:
 *
 *   биты 48..    что произошло: 0 нажали, 1 ведут, 2 отпустили
 *   биты 32..47  x
 *   биты 0..31   y
 *
 * Одним числом, а не тремя, потому что у машины нет ни структур, ни
 * возврата нескольких значений: приложение достаёт нужное делением и
 * остатком, как это делают на всяком маленьком языке. Отрицательное
 * число означает, что касаний больше не будет.
 */
#define VM_TOUCH_ACTION(v)  (((v) >> 48) & 0xFF)
#define VM_TOUCH_X(v)       (((v) >> 32) & 0xFFFF)
#define VM_TOUCH_Y(v)       ((v) & 0xFFFFFFFF)

/*
 * Запустить приложение.
 *
 * Возвращает 0, если приложение отработало и завершилось само.
 * Отрицательное — приложение остановлено машиной, и причина уже
 * напечатана через host->print: молча снимать программу нельзя, иначе
 * автор её никогда не починит.
 */
int vm_run(const void *image, vm_u32 len, const struct vm_host *host);

/* Имя приложения из заголовка; NULL, если файл не наш или испорчен */
const char *vm_app_name(const void *image, vm_u32 len);

#endif
