#ifndef HITTIS_VM_H
#define HITTIS_VM_H

/*
 * Виртуальная машина Hittis.
 *
 * Один и тот же исполнитель работает в двух местах: на компьютере, где
 * приложение проверяется без прошивки, и в телефоне, где он живёт
 * обычной программой в EL0. Разница между ними ровно одна — что делать,
 * когда приложение просит нарисовать или напечатать; поэтому всё
 * внешнее собрано в одну таблицу вызовов, а сама машина не знает ни про
 * системные вызовы, ни про printf.
 *
 * Машина недоверчива к приложению по построению. Она проверяет каждый
 * переход, каждое обращение к ячейке и глубину стека — и на любое
 * нарушение останавливается с внятной жалобой, а не портит память.
 * Приложение приходит с флешки, его мог испортить кто угодно, и «оно же
 * само себе не враг» здесь не работает.
 *
 * Машина не выделяет память вовсе: стек значений, кадры и глобальные
 * лежат в структуре, которую даёт вызывающий. На телефоне это важнее
 * всего — там просить память не у кого.
 */

typedef long long          vm_i64;
typedef unsigned int       vm_u32;
typedef unsigned short     vm_u16;
typedef unsigned char      vm_u8;

#define VM_STACK    256     /* глубина стека значений              */
#define VM_FRAMES   32      /* глубина вызовов                     */
#define VM_LOCALS   1024    /* общая площадь под кадры             */
#define VM_GLOBALS  256

/* Что машина умеет попросить у мира. Ничего сверх этого ей не видно. */
struct vm_host {
    void    (*print)(const char *s);
    void    (*printn)(vm_i64 v);
    int     (*window)(int w, int h);
    void    (*rect)(int x, int y, int w, int h, vm_u32 color);
    void    (*text)(int x, int y, int scale, vm_u32 color, const char *s);
    void    (*show)(void);
    vm_i64  (*touch)(void);         /* x в старшей половине, y в младшей */
    void    (*sleep_ms)(vm_i64 ms);
    vm_i64  (*time_ms)(void);
    int     (*width)(void);
    int     (*height)(void);
};

/*
 * Запустить приложение.
 *
 * Возвращает 0, если приложение отработало и завершилось само.
 * Отрицательное — приложение остановлено машиной, и причина уже
 * напечатана через host->print: молча снимать программу нельзя, иначе
 * автор её никогда не починит.
 */
int vm_run(const void *image, vm_u32 len, const struct vm_host *host);

/* Имя приложения из заголовка; NULL, если файл не наш или испорчен */
const char *vm_app_name(const void *image, vm_u32 len);

#endif
